# Nested result annotations resolve through the historical module namespace.
# Rebuild after every domain has exported its classes, just as if definitions
# still appeared together in this module.
for _result_type in tuple(globals().values()):
    if (
        isinstance(_result_type, type)
        and issubclass(_result_type, BaseModel)
        and _result_type.__module__ == __name__
        and not _result_type.__pydantic_complete__
    ):
        _result_type.model_rebuild()
del _result_type
