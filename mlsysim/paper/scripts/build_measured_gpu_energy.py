"""Build ``mlsysim/engine/data/measured_gpu_energy.yaml`` from the per-run tables.

The tables are in ``paper/data/serverless-gpu-energy/`` (its README describes
the measurements). This script turns them into the package table that
``mlsysim.engine.measured_energy`` reads:

- per GPU: loaded and reserved idle power, cold-start energy, the wait at
  which keeping a GPU warm costs as much as a cold start, the energy of a 60 s
  keep-warm window, and the energy of pausing a training job;
- the opt-in power model min(TDP, P_idle + (b x HFU + c x BWU) x TDP), with
  b and c fitted by least squares on a fixed grid over every power run, and
  its median error when each GPU, or each workload, is held out of the fit
  (conditional on measured idle power and throughput-scaled HFU and BWU).

Usage (from mlsysim/)::

    python paper/scripts/build_measured_gpu_energy.py          # write the table
    python paper/scripts/build_measured_gpu_energy.py --check  # exit 1 if stale
"""

from __future__ import annotations

import argparse
import csv
import sys
from collections import defaultdict
from pathlib import Path

import numpy as np
import yaml

ROOT = Path(__file__).resolve().parents[2]
DATA = ROOT / "paper" / "data" / "serverless-gpu-energy"
TABLE = ROOT / "mlsysim" / "engine" / "data" / "measured_gpu_energy.yaml"

# Modal GPU class -> MLSys·im registry key, in table order.
REGISTRY_KEY = {"T4": "T4", "L4": "L4", "A10": "A10", "A100-40GB": "A100_40GB",
                "H100": "H100", "H200": "H200", "B200": "B200"}
B_GRID = np.linspace(0.0, 8.0, 161)
C_GRID = np.linspace(0.0, 3.0, 121)
HEADER = (
    "# Generated by paper/scripts/build_measured_gpu_energy.py from paper/data/serverless-gpu-energy/.\n"
    "# Do not edit by hand: change the script or the data and rerun it.\n"
)


def read(name: str) -> list[dict]:
    with open(DATA / f"{name}.csv", newline="") as handle:
        return list(csv.DictReader(handle))


def mean(values) -> float:
    values = [float(v) for v in values]
    return sum(values) / len(values)


def fit_power_model(idle, hfu, bwu, y) -> tuple[float, float]:
    """Grid least squares of min(1, idle + b HFU + c BWU) against P / TDP.

    Ties go to the smallest b, then the smallest c.
    """
    pred = idle[None, None, :] + B_GRID[:, None, None] * hfu[None, None, :] + C_GRID[None, :, None] * bwu[None, None, :]
    sse = ((np.minimum(1.0, pred) - y[None, None, :]) ** 2).sum(axis=2)
    i, j = np.unravel_index(int(np.argmin(sse)), sse.shape)
    return float(B_GRID[i]), float(C_GRID[j])


def power_model(idle_w: dict[str, float]) -> tuple[dict, dict]:
    runs = read("power_runs")
    tdp = {}
    for r in runs:
        if tdp.setdefault(r["gpu"], float(r["tdp_w"])) != float(r["tdp_w"]):
            raise ValueError(f"{r['gpu']}: runs disagree on TDP")
    gpu = np.array([r["gpu"] for r in runs])
    workload = np.array([r["workload"] for r in runs])
    tdp_w = np.array([tdp[g] for g in gpu])
    measured = np.array([float(r["measured_power_w"]) for r in runs])
    idle = np.array([idle_w[g] for g in gpu]) / tdp_w
    hfu = np.array([float(r["hfu"]) for r in runs])
    bwu = np.array([float(r["bwu"]) for r in runs])
    engine = np.array([float(r["engine_power_w"]) for r in runs])
    y = measured / tdp_w

    def predict(mask, b, c):
        return np.minimum(1.0, idle[mask] + b * hfu[mask] + c * bwu[mask]) * tdp_w[mask]

    held_out = {}
    for name, groups in (("gpu", gpu), ("workload", workload)):
        pred = np.empty_like(measured)
        for key in np.unique(groups):
            train, test = groups != key, groups == key
            b, c = fit_power_model(idle[train], hfu[train], bwu[train], y[train])
            pred[test] = predict(test, b, c)
        held_out[name] = float(np.median(np.abs(pred / measured - 1.0)) * 100.0)
    b, c = fit_power_model(idle, hfu, bwu, y)
    model = {
        "form": "min(TDP, loaded_idle_power_w + (b_hfu * HFU + c_bwu * BWU) * TDP)",
        "b_hfu": round(b, 3),
        "c_bwu": round(c, 3),
        "fit": f"least squares over {len(runs)} power runs on {len(tdp)} GPUs and {len(set(workload))} workloads "
               "(grid: b from 0 to 8 in steps of 0.05, c from 0 to 3 in steps of 0.025)",
        "median_abs_error_pct_leave_one_gpu_out": round(held_out["gpu"], 1),
        "median_abs_error_pct_leave_one_workload_out": round(held_out["workload"], 1),
        "median_abs_error_pct_engine_default": round(float(np.median(np.abs(engine / measured - 1.0)) * 100.0), 1),
        "evaluation": "Exploratory, within these runs. Hold-out errors refit b and c without one GPU or one "
                      "workload and are conditional on each GPU's measured idle power and on HFU and BWU scaled "
                      "by measured throughput. The form was chosen after inspecting the first runs. The H200, "
                      "B200 and W6 runs came after it was fixed. Not a prospective accuracy.",
    }
    return model, tdp


def build() -> str:
    idle_runs, cold_runs = defaultdict(list), defaultdict(list)
    for r in read("idle_runs"):
        idle_runs[r["gpu"]].append(r)
    for r in read("coldstart_runs"):
        cold_runs[r["gpu"]].append(r)
    loaded_idle = {g: mean(r["idle_steady_power_w"] for r in rs) for g, rs in idle_runs.items()}
    model, tdp = power_model(loaded_idle)

    steps = defaultdict(dict)
    for r in read("pause_steps"):
        steps[(r["gpu"], r["workload"], r["repeat"])][r["step"]] = r
    pause = defaultdict(list)
    for (gpu, workload, _), s in sorted(steps.items()):
        steady = float(s["steady"]["energy_j"]) / float(s["steady"]["units"])
        excess = float(s["resume"]["energy_j"]) - steady * float(s["resume"]["units"])
        pause[(gpu, workload)].append(float(s["save"]["energy_j"]) + float(s["load"]["energy_j"]) + max(excess, 0.0))

    gpus = {}
    for gpu, key in REGISTRY_KEY.items():
        reserved = mean(r["idle_power_w"] for r in idle_runs[gpu])
        cold = [float(r["coldstart_energy_j"]) for r in cold_runs[gpu]]
        row = {
            "tdp_w": int(tdp[gpu]) if tdp[gpu].is_integer() else tdp[gpu],
            "loaded_idle_power_w": round(loaded_idle[gpu], 2),
            "reserved_idle_power_w": round(reserved, 2),
            "coldstart_energy_j": round(mean(cold), 1),
            "coldstart_repeats": len(cold),
            "crossover_wait_s": round(mean(e / reserved for e in cold), 2),
            "keepwarm_60s_energy_j": round(mean(r["keepwarm_60s_energy_j"] for r in idle_runs[gpu]), 1),
        }
        overhead = {w: round(mean(v), 1) for (g, w), v in sorted(pause.items()) if g == gpu}
        if overhead:
            row["pause_overhead_j"] = overhead
        gpus[key] = row

    doc = {
        "provenance": {
            "kind": "derived",
            "ref": "MLSys·im paper data: paper/data/serverless-gpu-energy (GPU board energy on Modal serverless "
                   "GPUs, NVML total-energy counter, November 2026)",
            "verified": "2026-11-12",
            "notes": "Board energy only: host CPU, memory, networking and facility energy are excluded. "
                     "loaded_idle_power_w is the mean over the last 300 s of a 600 s idle period with "
                     "Qwen2.5-1.5B loaded, and reserved_idle_power_w the mean over the whole 600 s, so the decay "
                     "right after the job is included (3 runs per GPU). coldstart_energy_j runs from the first "
                     "NVML read in a fresh container to the first generated token (GPU energy before the "
                     "function body starts is not visible). crossover_wait_s is cold-start energy over reserved "
                     "idle power. pause_overhead_j is checkpoint save plus load plus the resume's energy above "
                     "steady training, floored at zero. HFU and BWU in the power runs are MLSys·im's roofline "
                     "utilization scaled by measured over predicted throughput.",
            "id": "prov:mlsysim-serverless-gpu-energy-2026",
        },
        "power_model": model,
        "gpus": gpus,
    }
    return HEADER + yaml.safe_dump(doc, sort_keys=False, width=100, allow_unicode=True)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="exit 1 if the committed table differs")
    args = parser.parse_args(argv)
    text = build()
    if args.check:
        if TABLE.read_text() != text:
            print(f"{TABLE.relative_to(ROOT)} is stale; rerun {Path(__file__).name}", file=sys.stderr)
            return 1
        print(f"{TABLE.relative_to(ROOT)} matches paper/data/serverless-gpu-energy")
        return 0
    TABLE.write_text(text)
    print(f"wrote {TABLE.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
