"""Verify publication artifacts against their inputs and timing samples.

Hashes detect drift, not whether a measurement was honestly performed. Independent
execution remains necessary before presenting local timings as reproduced results.
All manifest paths are relative to the mlsysim project directory. The invocation
is recorded as a portable equivalent, not as a machine-local executable path.
"""

from __future__ import annotations

from datetime import datetime, timezone
import hashlib
from importlib import metadata
import json
import math
from pathlib import Path
import re
import statistics
import subprocess
import sys


# This protocol is declared before measurement; durations are never prescribed.
TIMING_PROTOCOL = {
    "section_instructor.<locals>.<lambda>": (5, 1, "CaseIOneSweepMs", 1e3),
    "section_researchers.<locals>.chain": (5, 1, "CaseRThreeChainSeconds", 1.0),
    "section_overview": (1, 0, "OverviewDSolveSeconds", 1.0),
    "section_timing.<locals>.sweep": (5, 1, "SweepTimingMedianMs", 1e3),
}
REPLAY_COMMAND = ["python", "paper/scripts/generate_paper_values.py"]
REPLAY_INSTRUCTIONS = {"cwd": "mlsysim project directory", "argv": REPLAY_COMMAND,
                       "environment": {"PYTHONPATH": "."}}
REQUIRED_DEPENDENCIES = ("pint", "pydantic", "numpy", "PyYAML", "matplotlib", "pytest")


def render_values_tex(records: dict) -> str:
    """Serialize the complete displayed macro file, including source comments."""
    lines = ["% Generated by mlsysim/paper/scripts/generate_paper_values.py. Do not edit by hand.",
             "% Regenerate with `make values` in mlsysim/paper/. Raw values: generated/values.json.",
             "% Percent macros (*Pct) print the number without the percent sign."]
    current = None
    for name, rec in records.items():
        if rec["section"] != current:
            current = rec["section"]
            lines += ["", f"% ===== {current} ====="]
        lines.append(f"\\newcommand{{\\{name}}}{{{rec['tex']}}}% source: {rec['source']}")
    return "\n".join(lines) + "\n"


def source_paths(root: Path) -> list[Path]:
    """Enumerate inputs rather than trusting a receipt to choose what gets checked."""
    paths = [root / "pyproject.toml"]
    for directory, suffixes in (("mlsysim", (".py", ".yaml", ".yml")),
                                ("tests", (".py",)),
                                ("paper/scripts", (".py",)),
                                ("paper/data", (".csv", ".json"))):
        paths.extend(p for p in (root / directory).rglob("*")
                     if p.is_file() and p.suffix in suffixes)
    return sorted(paths)


def output_paths(root: Path) -> list[Path]:
    """Artifacts emitted or synchronized by the paper-value generator."""
    generated = root / "paper/generated"
    paths = [generated / "values.json", generated / "values.tex",
             generated / "hw_catalog.tex", generated / "infra_systems.tex"]
    paths += sorted((root / "paper/figures").glob("*.svg"))
    # PDFs are ignored build products, absent from a fresh checkout/source archive.
    # Hash their tracked SVG sources here; inspect compiled PDFs during publication.
    return paths


def file_hashes(root: Path, paths: list[Path]) -> dict[str, str]:
    """Hash file content with portable paths relative to the project root."""
    return {p.relative_to(root).as_posix(): hashlib.sha256(p.read_bytes()).hexdigest()
            for p in paths}


def write_timing_receipt(root: Path, records: dict, samples: list[dict],
                         initial_source_hashes: dict[str, str]) -> None:
    """Write durations and a portable equivalent of the generating invocation.

    Host-specific executable and checkout paths belong in private run logs. The
    committed receipt retains Python/dependency versions and explicit path bases
    so another checkout or source archive can replay the same calculation.
    """
    source_hashes = file_hashes(root, source_paths(root))
    if source_hashes != initial_source_hashes:
        raise ValueError("source inputs changed during generation; rerun after edits finish")
    receipt = {
        "schema_version": 2,
        "kind": "local wall-clock measurements, not hardware-model accuracy",
        "timestamp_utc": datetime.now(timezone.utc).isoformat(),
        "path_base": "mlsysim project root",
        "working_directory": ".",
        "project_directory": ".",
        "hash_path_base": "project_directory",
        "command_kind": "normalized equivalent invocation",
        "command": REPLAY_COMMAND,
        "replay": REPLAY_INSTRUCTIONS,
        "code_sha": subprocess.check_output(["git", "rev-parse", "HEAD"], cwd=root, text=True).strip(),
        "dirty": bool(subprocess.check_output(["git", "status", "--porcelain"], cwd=root, text=True).strip()),
        "source_sha256": source_hashes,
        "output_sha256": file_hashes(root, output_paths(root)),
        "seed": None,
        "seed_status": "not applicable: deterministic workload; wall-clock durations vary",
        "python": sys.version,
        "dependencies": {d.metadata["Name"]: d.version for d in metadata.distributions()
                         if d.metadata["Name"]},
        "machine": {name: records[name]["raw"] for name in
                    ("MachineCpu", "MachineCores", "MachineOs", "MachinePython")},
        "protocol": {name: {"runs": spec[0], "warmup_runs": spec[1]}
                     for name, spec in TIMING_PROTOCOL.items()},
        "preregistration": {
            "status": "not independently preregistered",
            "reference": None,
            "protocol_source": "paper/scripts/paper_integrity.py",
            "protocol_source_sha256": source_hashes["paper/scripts/paper_integrity.py"],
            "interpretation": "descriptive local runtime, not a hypothesis test or accuracy benchmark",
        },
        "samples": samples,
    }
    (root / "paper/generated/timing_samples.json").write_text(
        json.dumps(receipt, indent=2, sort_keys=True) + "\n", encoding="utf-8")


def _positive_number(value) -> bool:
    return (isinstance(value, (int, float)) and not isinstance(value, bool)
            and math.isfinite(value) and value > 0)


def check_timing_receipt(root: Path, records: dict, generated_dir: Path | None = None) -> list[str]:
    """Reject missing, stale, malformed, or internally inconsistent timing evidence.

    This verifies links and arithmetic. It cannot detect a coordinated invention
    of samples, outputs, and hashes; the independent reviewer must rerun timings.
    The current machine need not match the recorded measuring environment.
    """
    path = (generated_dir or root / "paper/generated") / "timing_samples.json"
    try:
        receipt = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, ValueError) as exc:
        return [f"timing receipt missing or invalid: {exc}"]
    if not isinstance(receipt, dict):
        return ["timing receipt must be an object"]
    problems = []
    if receipt.get("schema_version") != 2:
        problems.append("timing receipt schema_version must be 2; regenerate portable run evidence")
    try:
        timestamp = datetime.fromisoformat(receipt.get("timestamp_utc", ""))
        if timestamp.tzinfo is None:
            raise ValueError("timezone missing")
    except (ValueError, TypeError):
        problems.append("timing receipt timestamp must include a timezone")
    if receipt.get("path_base") != "mlsysim project root":
        problems.append("timing receipt path_base must identify the mlsysim project root")
    for key in ("working_directory", "project_directory"):
        if receipt.get(key) != ".":
            problems.append(f"timing receipt {key} must be project-relative '.'")
    if receipt.get("hash_path_base") != "project_directory":
        problems.append("timing receipt hash_path_base must be project_directory")
    if receipt.get("command_kind") != "normalized equivalent invocation":
        problems.append("timing receipt must identify its normalized invocation")
    if receipt.get("command") != REPLAY_COMMAND:
        problems.append("timing receipt command must be the portable generator invocation")
    if receipt.get("replay") != REPLAY_INSTRUCTIONS:
        problems.append("timing receipt replay instructions differ from the generator invocation")
    if not isinstance(receipt.get("code_sha"), str) or not re.fullmatch(r"[0-9a-f]{40}", receipt["code_sha"]):
        problems.append("timing receipt code_sha must identify the recording checkout")
    if not isinstance(receipt.get("dirty"), bool):
        problems.append("timing receipt dirty must be boolean")
    if not isinstance(receipt.get("python"), str) or not receipt["python"]:
        problems.append("timing receipt Python version is missing")
    if "seed" not in receipt or not receipt.get("seed_status"):
        problems.append("timing receipt random-seed status is missing")
    deps = receipt.get("dependencies", {})
    if not isinstance(deps, dict) or any(not isinstance(v, str) or not v for v in deps.values()):
        problems.append("timing receipt dependencies must record package versions")
        deps = {}
    normalized = {str(k).lower().replace("_", "-") for k in deps}
    if any(name.lower().replace("_", "-") not in normalized for name in REQUIRED_DEPENDENCIES):
        problems.append("timing receipt lacks required dependency versions")
    for field, paths in (("source_sha256", source_paths(root)), ("output_sha256", output_paths(root))):
        try:
            expected = file_hashes(root, paths)
        except OSError as exc:
            problems.append(f"timing receipt {field}: required file missing: {exc}")
            continue
        actual = receipt.get(field)
        if not isinstance(actual, dict):
            problems.append(f"timing receipt {field} is missing")
            continue
        if set(actual) != set(expected):
            problems.append(f"timing receipt {field} file inventory differs")
        for name, digest in expected.items():
            if actual.get(name) != digest:
                problems.append(f"timing receipt {field} stale: {name}")
    prereg = receipt.get("preregistration")
    recorded_sources = receipt.get("source_sha256")
    if not isinstance(recorded_sources, dict):
        recorded_sources = {}
    if (not isinstance(prereg, dict) or prereg.get("status") != "not independently preregistered"
            or prereg.get("reference") is not None
            or prereg.get("protocol_source") != "paper/scripts/paper_integrity.py"
            or not prereg.get("interpretation")
            or prereg.get("protocol_source_sha256") != recorded_sources.get("paper/scripts/paper_integrity.py")):
        problems.append("timing receipt preregistration status/protocol linkage is invalid")
    machine = receipt.get("machine", {})
    machine_keys = {"MachineCpu", "MachineCores", "MachineOs", "MachinePython"}
    if (not isinstance(machine, dict) or set(machine) != machine_keys
            or any(machine.get(k) != records.get(k, {}).get("raw") for k in machine_keys)):
        problems.append("timing receipt machine differs from displayed machine values")
    expected_protocol = {name: {"runs": spec[0], "warmup_runs": spec[1]} for name, spec in TIMING_PROTOCOL.items()}
    if receipt.get("protocol") != expected_protocol:
        problems.append("timing receipt protocol differs from declared sampling protocol")
    samples = receipt.get("samples")
    if not isinstance(samples, list) or not all(isinstance(s, dict) for s in samples):
        return problems + ["timing receipt samples must be a list of measurements"]
    names = [s.get("function") for s in samples]
    if len(names) != len(TIMING_PROTOCOL) or set(str(n) for n in names) != set(TIMING_PROTOCOL):
        problems.append("timing receipt must contain exactly one sample group per timed scenario")
    for sample in samples:
        name = sample.get("function")
        if not isinstance(name, str) or name not in TIMING_PROTOCOL:
            continue
        runs, warmup, macro, scale = TIMING_PROTOCOL[name]
        seconds = sample.get("seconds")
        if (not isinstance(seconds, list) or len(seconds) != runs
                or not all(_positive_number(s) for s in seconds)):
            problems.append(f"timing receipt {name}: expected {runs} finite positive durations")
            continue
        if sample.get("warmup_runs") != warmup:
            problems.append(f"timing receipt {name}: wrong warmup count")
        median = statistics.median(seconds)
        if runs > 1 and sample.get("median_seconds") != median:
            problems.append(f"timing receipt {name}: median does not match raw durations")
        raw = records.get(macro, {}).get("raw")
        if not _positive_number(raw) or not math.isclose(raw, median * scale, rel_tol=1e-12):
            problems.append(f"timing receipt {name}: samples do not reproduce {macro}")
    config_count = records.get("SweepTimingConfigs", {}).get("raw")
    sweep_ms = records.get("SweepTimingMedianMs", {}).get("raw")
    per_config = records.get("SweepTimingPerConfigUs", {}).get("raw")
    if (config_count != 1000 or not _positive_number(sweep_ms) or not _positive_number(per_config)
            or not math.isclose(per_config, sweep_ms * 1e3 / config_count, rel_tol=1e-12)):
        problems.append("timing receipt sweep count/per-configuration arithmetic is inconsistent")
    return problems
