def check(deck, vol, rules):
    findings = []

    def out(rule, sev, slide, line, msg):
        findings.append(Finding(deck.name, slide, line, sev, rule, msg))

    if not deck.tex_path:
        out("notes", "error", None, None, "no .tex file in the deck folder")
        return findings
    for r in rules:
        RULES[r](deck, vol, out)
    findings.sort(key=lambda f: (f.slide or 0, f.line or 0, f.rule))
    return findings


def resolve(args):
    """Return [(Volume, [Deck])]."""
    vols = {}

    def volume(vdir):
        vdir = Path(vdir).resolve()
        if vdir not in vols:
            vols[vdir] = (Volume(vdir, args.concepts_root), [])
        return vols[vdir]

    targets = list(args.decks)
    if args.all:
        names = [t for t in targets if re.fullmatch(r"vol\d", Path(t).name)] or \
            sorted(p.name for p in ROOT.glob("vol[0-9]") if p.is_dir())
        for n in names:
            v, lst = volume(Path(n) if Path(n).is_dir() else ROOT / Path(n).name)
            lst.extend(v.decks)
        return list(vols.values())
    for t in targets:
        p = Path(t)
        if not p.exists():
            p = ROOT / t
        p = p.resolve()
        if p.is_file():
            p = p.parent
        if re.fullmatch(r"vol\d", p.name):
            v, lst = volume(p)
            lst.extend(v.decks)
            continue
        v, lst = volume(p.parent)
        d = next((d for d in v.decks if d.path == p), None)
        if d is None:
            sys.exit(f"deckcheck: {t} is not a deck folder (slides/volN/<NN>_<name>/ with a .tex)")
        lst.append(d)
    return list(vols.values())


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("decks", nargs="*", help="deck folders (vol1/10b_model_compression) or a volume (vol1)")
    ap.add_argument("--all", action="store_true", help="every deck (of the volumes named, or of all volumes)")
    ap.add_argument("--rule", action="append", choices=sorted(RULES), help="run only these rules")
    ap.add_argument("--errors-only", action="store_true", help="print errors only")
    ap.add_argument("--concepts-root", help="book source for the volume (holds <chapter>/*_concepts.yml)")
    ap.add_argument("--summary", action="store_true", help="end with counts per rule")
    a = ap.parse_args()
    if not a.decks and not a.all:
        ap.error("name a deck folder, a volume, or --all")
    rules = a.rule or list(RULES)
    n_err = n_warn = 0
    per_rule = Counter()
    for vol, decks in resolve(a):
        for d in decks:
            for f in check(d, vol, rules):
                per_rule[(f.rule, f.sev)] += 1
                if f.sev == "error":
                    n_err += 1
                else:
                    n_warn += 1
                    if a.errors_only:
                        continue
                print(f)
    if a.summary:
        for (r, s), n in sorted(per_rule.items()):
            print(f"  {r:14s} {s:7s} {n}")
    print(f"deckcheck: {n_err} error{'s' * (n_err != 1)}, {n_warn} warning{'s' * (n_warn != 1)}")
    sys.exit(1 if n_err else 0)


if __name__ == "__main__":
    main()
