class Finding:
    def __init__(self, deck, slide, line, sev, rule, msg):
        self.deck, self.slide, self.line = deck, slide, line
        self.sev, self.rule, self.msg = sev, rule, msg

    def __str__(self):
        where = f"slide {self.slide}" if self.slide else "deck"
        if self.line:
            where += f" (line {self.line})"
        return f"{self.deck} {where} {self.sev} {self.rule}: {self.msg}"


def match_brace(s, i):
    """s[i] == '{'; return the index just past its matching '}'."""
    depth = 0
    n = len(s)
    while i < n:
        c = s[i]
        if c == "\\":
            i += 2
            continue
        if c == "{":
            depth += 1
        elif c == "}":
            depth -= 1
            if depth == 0:
                return i + 1
        i += 1
    return n


def brace_args(s, i, count):
    """Read `count` brace groups starting at or after s[i] (skipping
    whitespace, [opt] and <overlay>). Return ([args], end)."""
    args = []
    n = len(s)
    while len(args) < count and i < n:
        while i < n and s[i] in " \t\n":
            i += 1
        if i < n and s[i] == "[":
            j = s.find("]", i)
            i = j + 1 if j > 0 else n
            continue
        if i < n and s[i] == "<":
            j = s.find(">", i)
            i = j + 1 if j > 0 else n
            continue
        if i < n and s[i] == "{":
            j = match_brace(s, i)
            args.append(s[i + 1:j - 1])
            i = j
        else:
            break
    return args, i


def strip_comments(tex):
    """Blank out % comments, keeping every offset and newline in place."""
    out = []
    for line in tex.split("\n"):
        m = re.search(r"(?<!\\)%", line)
        if m:
            line = line[:m.start()] + " " * (len(line) - m.start())
        out.append(line)
    return "\n".join(out)


