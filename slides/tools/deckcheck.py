def rule_cover(deck, vol, out):
    title = next((f for f in deck.frames if f.kind == "title"), None)
    if not title:
        out("cover", "error", None, None, "no \\mlsystitle title slide")
        return
    img = getattr(title, "image", "").strip()
    name = Path(img).name
    if not img:
        out("cover", "error", title.num, title.line, "the title slide has no image")
        return
    # A credited photo is acceptable.
    for src in (deck.path / "images" / "SOURCES.yml", ROOT / "assets" / "photos" / "SOURCES.yml"):
        if src.exists() and re.search(r"file:\s*\"?%s\"?\s*$" % re.escape(name), src.read_text(), re.M):
            return
    path = None
    for cand in (deck.path / "images" / img, deck.path / img):
        if cand.exists():
            path = cand
            break
    verdict = None   # what the book cover it resembles is
    if path and vol.book:
        verdict = compare_cover(path, vol.book / deck.chapter / "images" / "png")
    if re.search(r"_blueprint\.(png|jpg)$", name) and verdict in (None, "blueprint"):
        return
    if verdict == "blueprint":
        out("cover", "warning", title.num, title.line,
            f"{name} is the blueprint cover under an old name; rename it to *_blueprint.png")
        return
    if verdict == "labeled":
        out("cover", "error", title.num, title.line,
            f"{name} is a labeled print cover; use the clean cover_<chapter>_blueprint.png")
        return
    if verdict == "old" or re.match(r"cover_.*\.png$", name):
        out("cover", "error", title.num, title.line,
            f"{name} is an old generated cover (garbled baked-in text); use cover_<chapter>_blueprint.png")
        return
    out("cover", "error", title.num, title.line,
        f"{img} is neither a *_blueprint.png nor a photo credited in a SOURCES.yml")


def compare_cover(path, bookdir):
    """Classify an image by its nearest book cover: blueprint, labeled, old, or None."""
    try:
        from PIL import Image
    except ImportError:
        return None
    if not bookdir.exists():
        return None

    def sig(p):
        im = Image.open(p).convert("L").resize((32, 18))
        return list(im.tobytes())

    try:
        a = sig(path)
    except Exception:
        return None
    best = None
    for c in bookdir.glob("cover_*.png"):
        try:
            b = sig(c)
        except Exception:
            continue
        dist = sum(abs(x - y) for x, y in zip(a, b)) / len(a)
        if best is None or dist < best[0]:
            best = (dist, c.name)
    if not best or best[0] > 8:
        return None
    n = best[1]
    if n.endswith("_blueprint.png"):
        return "blueprint"
    if "_blueprint" in n:
        return "labeled"
    return "old"


LECTURE_RE = re.compile(
    r"\bLectures?[ ~]+(\d{1,2}[a-z]?\b(?:'s)?(?:(?:\s*,\s*(?:and\s+)?|\s+and\s+|\s+or\s+|\s+to\s+|\s*(?:--|–|-)\s*)\d{1,2}[a-z]?\b(?:'s)?)*)")
COURSE_RE = re.compile(r"(CS\s?\d+|6\.\d+|EE\s?\d+|Stanford|MIT|Berkeley|Fatahalian)[^.]{0,25}$")

# Words too common to say which lecture owns something.
CALLBACK_STOP = set("""
token tokens flop flops multiply multiplie fast faster slow cost costs time data byte bytes
lecture lectures part today slide slides note notes step steps show showed shows
taught teach teaches named name names covered cover covers built build builds
introduced owns own owned return returns next earlier later chapter section
number numbers measure measured model models system systems same one two three
""".split())


def iter_callbacks(deck):
    """Yield (kind, offset or None, context, ids, where_label) for every mention."""
    raw = deck.raw.replace("~", " ")
    src = deck.src.replace("~", " ")
    for m in LECTURE_RE.finditer(raw):
        kind = "comment" if src[m.start():m.end()].strip() == "" else "tex"
        if COURSE_RE.search(raw[max(0, m.start() - 40):m.start()]):
            continue
        ids = re.findall(r"\d{1,2}[a-z]?", m.group(1))
        yield kind, m.start(), window(raw, m), ids, None
    for name, text in (("make_figs.py", deck.make_figs),
                       ("lecture_map.yml", (deck.path / "lecture_map.yml").read_text(errors="replace")
                        if (deck.path / "lecture_map.yml").exists() else "")):
        lines = text.split("\n")
        for ln, line in enumerate(lines, 1):
            for m in LECTURE_RE.finditer(line):
                if COURSE_RE.search(line[max(0, m.start() - 40):m.start()]):
                    continue
                ids = re.findall(r"\d{1,2}[a-z]?", m.group(1))
                yield name, None, window(line, m), ids, f"{name}:{ln}"


def window(s, m):
    """The words that belong to one mention, within its clause and never past a
    neighboring mention: a parenthetical "X (Lecture N)" owns the words before
    it; "Lecture N: a, b, c" owns its list; otherwise up to eight words before
    the mention and six after it, stopping at a comma."""
    a, b = m.start(), m.end()
    lo_c, hi_c = clause_bounds(s, a, b)
    prev = [x.end() for x in LECTURE_RE.finditer(s, lo_c, a)]
    nxt = LECTURE_RE.search(s, b, hi_c) if b < hi_c else None
    lo = max([lo_c] + prev)
    hi = nxt.start() if nxt else hi_c
    if s[max(0, a - 1):a] == "(":
        before = s[lo:a - 1]
        cut = max(before.rfind(", "), before.rfind("("))
        return before[cut + 1:] if cut >= 0 else before
    if re.match(r"\s*:", s[b:b + 3]):
        return s[a:hi]
    pre = s[lo:a]
    cut = pre.rfind(", ")
    pre = pre[cut + 2:] if cut >= 0 else pre
    pre = " ".join(pre.split()[-8:])
    post = s[b:hi]
    cut = post.find(", ")
    post = post[:cut] if cut >= 0 else post
    post = " ".join(post.split()[:6])
    return f"{pre} {s[a:b]} {post}"


def clause_bounds(s, a, b):
    lo = max(s.rfind(c, 0, a) + len(c) for c in (";", ". ", ": ", "\n\n", "\n%", '", "', "{"))
    his = [s.find(c, b) for c in (";", ". ", "\n\n", "\n%", '", "', "}")]
    his = [h for h in his if h >= 0]
    return max(lo, 0), (min(his) if his else len(s))


PROVENANCE = re.compile(r"\b(moved|copied) (from|to|into)\b|\bformerly\b|\bwas in\b|\bafter the split\b", re.I)


def rule_callbacks(deck, vol, out):
    idx = vol.index()
    strong = vol.strong()
    sdf = Counter()
    for ws in strong.values():
        sdf.update(ws)
    seen = set()
    for kind, off, ctx, ids, label in iter_callbacks(deck):
        slide, line = deck.where(off) if off is not None else (None, None)
        loc = label or ""
        norms = [re.sub(r"^0+(?=\d)", "", x) for x in ids]
        for lid, norm in zip(ids, norms):
            if norm not in vol.by_id:
                key = (norm, slide, line, loc)
                if key in seen:
                    continue
                seen.add(key)
                out("callbacks", "error", slide, line,
                    f"{('[' + loc + '] ') if loc else ''}names Lecture {lid}, which is not a deck in {vol.name}")
                continue
            sib = vol.sibling(norm)
            # Skip: the deck itself, its own other part (contrast is expected there),
            # a lecture without a second part, both parts named together, provenance notes.
            if norm == deck.id or sib == deck.id or sib not in vol.by_id or sib in norms \
                    or PROVENANCE.search(ctx):
                continue
            plain = detex(ctx)
            terms = {stem(w) for w in words(plain) if len(w) >= 4}
            terms |= {stem(w) for w in re.findall(r"\b[A-Z][A-Z0-9-]{1,6}\b", ctx)}
            # A term the other part names as its topic (title, segment name, or
            # taught concept), that at most one other lecture names that way,
            # and that the cited lecture's map never mentions.
            bad = sorted(t for t in terms
                         if t not in CALLBACK_STOP and t in strong[sib] and sdf[t] <= 2
                         and t not in idx[norm]
                         and not ("-" in t and all(stem(x) in idx[norm] for x in t.split("-") if x))
                         and not re.fullmatch(r"[\d.]+[a-z]?", t))
            if bad:
                key = (norm, tuple(bad), slide, loc)
                if key in seen:
                    continue
                seen.add(key)
                snippet = re.sub(r"\s+", " ", plain)[:100]
                out("callbacks", "warning", slide, line,
                    f"{('[' + loc + '] ') if loc else ''}Lecture {lid} beside \"{', '.join(bad)}\", "
                    f"which Lecture {sib}'s map teaches and Lecture {norm}'s does not: \"{snippet}\"")


def norm_label(s):
    s = detex(s).upper()
    s = s.replace("&", "AND")
    s = re.sub(r"[^A-Z0-9, ]+", " ", s)
    s = re.sub(r"\s+", " ", s).strip()
    return re.sub(r"^THE ", "", s)


def rule_next(deck, vol, out):
    m = None
    for m in re.finditer(r"NEXT LECTURE\s*(?:\\textbar\{\}|\\textbar|\||\$\|\$)\s*([^}\\]*)", deck.src):
        pass
    nxt = vol.next_deck(deck)
    if not m:
        if nxt:
            out("next-lecture", "error", None, None,
                f"no closing \"NEXT LECTURE | ...\" label; expected {nxt.title.upper()}")
        return
    slide, line = deck.where(m.start())
    got = m.group(1).strip()
    if not nxt:
        out("next-lecture", "error", slide, line,
            f"the last deck of {vol.name} announces a next lecture (\"{got}\")")
        return
    if norm_label(got) != norm_label(nxt.title):
        out("next-lecture", "error", slide, line,
            f"says NEXT LECTURE | {got}; the next deck is Lecture {nxt.id}, \"{nxt.title}\" "
            f"(expected NEXT LECTURE | {nxt.title.upper()})")


KEEP_FILES = {"make_figs.py", "calcs.py", "SOURCES.yml"}
OUT_EXT = (".svg", ".pdf", ".png", ".jpg", ".jpeg")


def tex_uses(tex, stem_):
    return re.search(re.escape(stem_) + r"(?![A-Za-z0-9_])", tex) is not None


def shipped_files(images):
    """Names in images/ that git tracks or would add (not ignored); None without git."""
    import subprocess
    try:
        r = subprocess.run(["git", "-C", str(images), "ls-files", "--cached", "--others",
                            "--exclude-standard", "--", "."],
                           capture_output=True, text=True, timeout=30)
    except (OSError, subprocess.SubprocessError):
        return None
    if r.returncode != 0:
        return None
    return {Path(x).name for x in r.stdout.splitlines() if "/" not in x}


def rule_unused(deck, vol, out):
    images = deck.path / "images"
    if not images.exists():
        return
    tex = deck.raw
    gen = deck.make_figs
    steps = {}   # \mlsyssteps{name}{n}
    for m in re.finditer(r"\\mlsyssteps\s*(?:\[[^\]]*\])?\s*\{([^}]*)\}\s*\{(\d+)\}", deck.src):
        steps[Path(m.group(1)).name] = int(m.group(2))

    def used_by_tex(st):
        if tex_uses(deck.src, st):
            return True
        m = re.match(r"(.*?)(\d+)$", st)
        if m and m.group(1) in steps:
            return 1 <= int(m.group(2)) <= steps[m.group(1)]
        prefix = re.sub(r"\d+$", "", st)
        return bool(prefix and prefix != st and prefix in deck.src and prefix not in steps)

    shipped = shipped_files(images)
    reported = set()
    for f in sorted(images.iterdir()):
        if f.is_dir() or f.name in KEEP_FILES or f.name.startswith("."):
            continue
        # Companion scripts (calcs.py, trace and data scripts) are source, not images;
        # the old-deck generator name make_figures.py is the one script that is stale.
        if f.suffix == ".py" and f.name != "make_figures.py":
            continue
        if f.suffix in (".csv", ".json") and (images / "data").exists() is False and f.parent == images:
            pass
        if shipped is not None and f.name not in shipped:
            continue   # an ignored build product (an SVG's PDF), not part of the deck
        st = f.stem
        if st in reported:
            continue
        reported.add(st)
        # tools/unused_images.py: used when the stem, or its stem without a step number,
        # appears in the .tex or make_figs.py.
        prefix = re.sub(r"\d+$", "", st)
        src = tex + gen
        listed = re.search(re.escape(st) + r"(?![A-Za-z0-9_])", src) or (prefix and prefix != st and prefix in src)
        if not listed:
            out("unused-images", "error", None, None, f"images/{f.name} is not used by the .tex or make_figs.py")
            continue
        if f.suffix.lower() in OUT_EXT and not used_by_tex(st):
            # A source the generator reads (an input photo or data) is not an output.
            if gen and re.search(r"(open|imread|read|load|Image\.open)\w*\([^)]*%s" % re.escape(f.name), gen):
                continue
            out("unused-images", "error", None, None,
                f"images/{f.name} is generated or named by make_figs.py but never shown by the .tex")
    # Generators whose outputs are not on disk and not used (stale generators).
    if gen:
        seen = set()
        for m in re.finditer(r"""f?["']([A-Za-z0-9_\-{}]+)\.(svg|pdf|png)["']""", gen):
            name = m.group(1)
            base = re.sub(r"\{[^}]*\}.*$", "", name)
            if not base or base in seen:
                continue
            seen.add(base)
            on_disk = any(images.glob(base + "*"))
            if on_disk:
                continue
            if "{" in name:
                if base in deck.src:
                    continue
            elif used_by_tex(base):
                continue
            out("unused-images", "warning", None, None,
                f"make_figs.py still generates {name}.{m.group(2)}, which the .tex does not use")


BRITISH = re.compile(r"\b(colou?r(?<=colour)\w*|behaviour\w*|favour\w*|optimis(?:e|ed|es|ing|ation|ations|er|ers)\b|"
                     r"minimis(?:e|ed|es|ing)\b|maximis(?:e|ed|es|ing)\b|normalis(?:e|ed|es|ing|ation)\b|"
                     r"centre[sd]?\b|modelling|modelled|labelled|labelling|travelled|cancelled|"
                     r"analys(?:e|ed|ing)\b|utilis(?:e|ed|es|ing|ation)\b|programme[sd]?\b|"
                     r"organis(?:e|ed|es|ing|ation)\b|grey\b)", re.I)
HYPE = re.compile(r"\b(crucial(?:ly)?|massive(?:ly)?|game[- ]changing|game[- ]changer|revolutionary|"
                  r"revolutioni[sz]e[sd]?|unprecedented|cutting[- ]edge)\b", re.I)


def rule_style(deck, vol, out):
    s = deck.src
    doc = max(0, s.find("\\begin{document}"))
    body = s[doc:]
    dashes = list(re.finditer(r"—|(?<!-)---(?!-)", body))
    if len(dashes) > 12:
        lines = compact(sorted({deck.line_of(doc + m.start()) for m in dashes}))
        out("style", "error", None, None, f"{len(dashes)} em dashes; lines {lines}")
        dashes = []
    for m in dashes:
        off = doc + m.start()
        slide, line = deck.where(off)
        if re.match(r"&\s*---\s*(&|\\\\)", s[off - 1:off + 8].lstrip()) or \
                re.search(r"&\s*$", s[max(0, off - 6):off]) and re.match(r"---\s*(&|\\\\)", s[off:off + 8]):
            out("style", "warning", slide, line,
                f"em dash as an empty table cell; prefer a blank cell or \"n/a\": \"{context(s, off)}\"")
            continue
        out("style", "error", slide, line, f"em dash: \"{context(s, off)}\"")
    # Prose regions only: slide text, titles, notes, credits.
    for f in deck.frames:
        regions = [("slide", f.text), ("note", detex(f.note))] + [("credit", detex(c)) for c in f.credits]
        for where, text in regions:
            for m in BRITISH.finditer(text):
                w = m.group(0)
                if re.search(r"(Centre|Programme)\b", w) and re.search(r"[A-Z]\w+ " + re.escape(w), text):
                    continue   # a proper noun: "Supercomputing Centre"
                out("style", "error", f.num, f.line, f"British spelling \"{w}\" in the {where}")
            if where == "credit":
                continue   # titles of cited papers are quoted as published
            for m in HYPE.finditer(text):
                out("style", "warning", f.num, f.line, f"hype word \"{m.group(0)}\" in the {where}")


def context(s, off, width=40):
    return re.sub(r"\s+", " ", s[max(0, off - width):off + width]).strip()


MIN_RE = re.compile(r"^\s*\[(\d+(?:\.\d+)?)\s*min\]")
TAG_RE = re.compile(r"\[(CORE|OPTIONAL)\b[^\]]*\]")


def note_minutes(text):
    m = MIN_RE.match(text)
    return float(m.group(1)) if m else None


CLOSING_TITLE = re.compile(r"^(Takeaways|Open questions|Read and explore|Read, practice|Five things)", re.I)


def is_structural(f):
    """Title, section dividers, and the closing run (takeaways, open questions,
    reading, the next-lecture frame): taught every time, so a missing tag
    loses nothing an instructor needs to decide."""
    return f.kind in ("title", "section") or (f.kind == "frame" and (
        not detex(f.title) or CLOSING_TITLE.match(detex(f.title))))


def compact(nums):
    """[1, 2, 3, 7, 9, 10] -> '1-3, 7, 9-10'."""
    out, i = [], 0
    while i < len(nums):
        j = i
        while j + 1 < len(nums) and nums[j + 1] == nums[j] + 1:
            j += 1
        out.append(f"{nums[i]}-{nums[j]}" if j > i else str(nums[i]))
        i = j + 1
    return ", ".join(out)


def rule_notes(deck, vol, out):
    for kind, off, msg in deck.findings_pre:
        if kind == "notes":
            slide, line = deck.where(off)
            out("notes", "error", slide, line, msg)
    total = 0.0
    untagged = []
    content = [f for f in deck.frames if not f.backup and f.kind != "backup"]
    noteless = [f for f in content if not f.notes]
    untimed = [f for f in content for text, _ in f.notes if note_minutes(text) is None]
    if len(noteless) > 8:
        out("notes", "error", None, None,
            f"{len(noteless)} of {len(content)} frames have no note: slides {compact([f.num for f in noteless])}")
    else:
        for f in noteless:
            out("notes", "error", f.num, f.line,
                f"{f.kind} frame \"{detex(f.title)[:50]}\" has no note")
    if len(untimed) > 8:
        out("notes", "error", None, None,
            f"{len(untimed)} notes do not open with [N min]: slides {compact(sorted({f.num for f in untimed}))}")
    for f in content:
        if not f.notes:
            continue
        if len(f.notes) > 1:
            out("notes", "warning", f.num, f.line, f"{len(f.notes)} notes on one frame; the notes page shows them run together")
        for text, off in f.notes:
            mins = note_minutes(text)
            if mins is None:
                if len(untimed) <= 8:
                    out("notes", "error", f.num, deck.line_of(off), "note does not open with [N min]")
            else:
                total += mins
            if not TAG_RE.search(text):
                untagged.append(f)
            n = len(detex(re.sub(r"\\[A-Za-z]+", " ", text)).split())
            if n > NOTE_WORD_LIMIT:
                out("notes", "error", f.num, deck.line_of(off),
                    f"note has {n} words (limit {NOTE_WORD_LIMIT}; the notes PDF truncates it)")
    # Title and section-divider notes are always taught; an untagged one is a
    # warning. An untagged content note (a slide or a focus slide) is an error:
    # the instructor cannot tell whether it can be cut.
    structural = [f for f in untagged if is_structural(f)]
    contentual = [f for f in untagged if not is_structural(f)]
    if structural:
        out("notes", "warning", None, None,
            f"{len(structural)} title, divider or closing note{'s carry' if len(structural) != 1 else ' carries'} no [CORE] tag: "
            f"slides {compact(sorted({f.num for f in structural}))}")
    if len(contentual) > 5:
        out("notes", "error", None, None,
            f"{len(contentual)} of {len(content)} slide notes carry no [CORE] or [OPTIONAL] tag: "
            f"slides {compact(sorted({f.num for f in contentual}))}")
    else:
        for f in contentual:
            out("notes", "error", f.num, f.line,
                f"note on \"{detex(f.title)[:50] or 'untitled ' + f.kind}\" carries no [CORE] or [OPTIONAL] tag")
    if not (NOTE_MIN <= total <= NOTE_MAX):
        out("notes", "error", None, None,
            f"notes total {total:g} minutes; the lecture needs {NOTE_MIN:g} to {NOTE_MAX:g}")


def rule_activity(deck, vol, out):
    content = [f for f in deck.frames if not f.backup]
    t, starts, total = 0.0, [], 0.0
    for f in content:
        if f.activity:
            starts.append((t, f))
        for text, _ in f.notes:
            t += note_minutes(text) or 0.0
    total = t
    if len(starts) < ACTIVITY_MIN_COUNT:
        out("activity", "error", None, None,
            f"{len(starts)} \\mlsysactivity frames; a lecture needs at least {ACTIVITY_MIN_COUNT}")
    if total == 0:
        return
    marks = [(0.0, None)] + starts + [(total, None)]
    for (a, fa), (b, fb) in zip(marks, marks[1:]):
        gap = b - a
        if gap <= ACTIVITY_GAP_WARN:
            continue
        sev = "error" if gap > ACTIVITY_GAP_ERR else "warning"
        frm = f"slide {fa.num} (minute {a:g})" if fa else "the start"
        to = f"slide {fb.num} (minute {b:g})" if fb else f"the end (minute {b:g})"
        slide = fb.num if fb else (fa.num if fa else None)
        out("activity", sev, slide, fb.line if fb else (fa.line if fa else None),
            f"{gap:g} minutes of notes without an activity, from {frm} to {to}")


# Helvetica metrics (the decks load helvet, scaled 0.9), from the TeX Live AFMs
# when available; a fallback table of average widths otherwise.
def _afm(name):
    import glob as _g
    for p in _g.glob(f"/usr/local/texlive/*/texmf-dist/fonts/afm/adobe/helvetic/{name}.afm") + \
            _g.glob(f"/usr/share/texlive/texmf-dist/fonts/afm/adobe/helvetic/{name}.afm"):
        w = {}
        for line in open(p, errors="replace"):
            m = re.match(r"C (-?\d+) ; WX (\d+) ; N (\S+)", line)
            if m:
                w[m.group(3)] = int(m.group(2))
        return w
    return None


