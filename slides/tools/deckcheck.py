def detex(s):
    """LaTeX to plain words, good enough for word matching and counting."""
    s = s.replace("~", " ")
    s = re.sub(r"\\(begin|end)\{[^}]*\}(\{[^}]*\})?", " ", s)
    # Arguments that are file names, sizes or styles, not words.
    for mac in GRAPHIC_MACROS:
        s = re.sub(r"\\%s\*?(\[[^\]]*\])?(<[^>]*>)?\{[^{}]*\}(\{[^{}]*\})?" % mac, " ", s)
    s = re.sub(r"\\(only|uncover|visible|alt|onslide|invisible|alert|item)\s*<[^>]*>", " ", s)
    s = re.sub(r"\\\\(\[[^\]]*\])?", " ", s)
    s = re.sub(r"\[[a-zA-Z ]*=[^\]]*\]", " ", s)            # [key=value] options
    s = re.sub(r"\(\s*-?[\d.]+\s*,\s*-?[\d.]+\s*\)", " ", s)  # TikZ coordinates
    s = re.sub(r"\(\s*[a-zA-Z]\w*(\.\w+)?\s*\)", " ", s)      # TikZ node names
    s = s.replace("\\%", "%").replace("\\$", "\x00").replace("\\&", "&")
    s = s.replace("\\textbar{}", "|").replace("\\textbar", "|")
    s = s.replace("\\times", " × ").replace("\\cdot", "·").replace("\\textperiodcentered", "·")
    s = re.sub(r"\\[a-zA-Z@]+\*?", " ", s)
    s = re.sub(r"[{}$]", " ", s).replace("\x00", "$")
    s = s.replace("---", "—").replace("--", "–").replace("``", "\u201c").replace("''", "\u201d")
    return re.sub(r"\s+", " ", s).strip()


def stem(w):
    """A light plural stemmer, used for set membership (ownership index)."""
    w = w.lower()
    for suf in ("ization", "isation"):
        if w.endswith(suf) and len(w) > 9:
            return w[: -len(suf)] + "ize"
    if w.endswith("ies") and len(w) > 5:
        return w[:-3] + "y"
    if re.search(r"(ss|x|z|ch|sh)es$", w) and len(w) > 5:
        return w[:-2]
    if w.endswith("s") and not re.search(r"(ss|us|is|as|os)$", w) and len(w) > 3:
        return w[:-1]
    return w


def root(w):
    """A shorter root for concept matching: 'tiling' and 'tiles' -> 'til',
    'quantization' and 'quantized' -> 'quantiz', 'partitioning' -> 'partition'."""
    w = stem(w)
    for suf in ("ization", "ations", "ation", "ities", "ity", "ings", "ing", "ers", "er",
                "ed", "es", "ly", "ive", "ion", "ize", "ise", "al", "e", "y"):
        if w.endswith(suf) and len(w) - len(suf) >= 3:
            return w[: -len(suf)]
    return w


def words(s):
    return re.findall(r"[A-Za-z][A-Za-z0-9]*(?:[-'][A-Za-z0-9]+)*", s)


def wordset(s):
    out = set()
    for w in words(s):
        out.add(stem(w))
        for part in re.split(r"[-']", w):      # "accuracy-efficiency" also counts its parts
            if part:
                out.add(stem(part))
    return out


def lecture_id(folder):
    """'04b_data_engineering' -> '4b', '00_course_overview' -> '0'."""
    m = re.match(r"(\d+)([a-z]?)_", folder)
    return f"{int(m.group(1))}{m.group(2)}" if m else None


def order_key(folder):
    m = re.match(r"(\d+)([a-z]?)_", folder)
    return (int(m.group(1)), m.group(2)) if m else (999, folder)


