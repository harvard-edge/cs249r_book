class Frame:
    def __init__(self, num, kind, start, end, line):
        self.num, self.kind, self.start, self.end, self.line = num, kind, start, end, line
        self.title = ""
        self.text = ""          # slide text: title and body, without notes and credits
        self.figtext = ""       # text labels of the SVG figures the frame shows
        self.credits = []
        self.notes = []         # (text, offset)
        self.activity = None    # (label, minutes string)
        self.backup = False

    @property
    def note(self):
        return " ".join(n for n, _ in self.notes)


class Deck:
    def __init__(self, path):
        self.path = Path(path).resolve()
        self.folder = self.path.name
        self.volume = self.path.parent.name
        self.id = lecture_id(self.folder)
        texs = sorted(self.path.glob("*.tex"))
        self.tex_path = next((t for t in texs if t.stem == self.folder), texs[0] if texs else None)
        self.raw = self.tex_path.read_text(errors="replace") if self.tex_path else ""
        self.src = strip_comments(self.raw)
        mp = self.path / "lecture_map.yml"
        try:
            self.map = yaml.safe_load(mp.read_text()) if mp.exists() else {}
        except yaml.YAMLError:
            self.map = {}
        self.map = self.map or {}
        gen = self.path / "images" / "make_figs.py"
        self.make_figs = gen.read_text(errors="replace") if gen.exists() else ""
        self.findings_pre = []   # parse-time findings
        self._newlines = [m.start() for m in re.finditer("\n", self.raw)]
        self.frames = self._parse()
        self._attach_figure_text()

    @property
    def name(self):
        return f"{self.volume}/{self.folder}"

    @property
    def title(self):
        if self.map.get("title"):
            return str(self.map["title"])
        m = re.search(r"chaptertitle=\{([^}]*)\}", self.src) or re.search(r"\\title\{([^}]*)\}", self.src)
        return detex(m.group(1)) if m else self.folder

    @property
    def chapter(self):
        ch = self.map.get("chapter")
        if ch:
            return str(ch)
        m = re.match(r"(\d+)[a-z]?_(.*)", self.folder)
        return f"{m.group(1)}_{m.group(2)}" if m else self.folder

    def line_of(self, off):
        lo, hi = 0, len(self._newlines)
        while lo < hi:
            mid = (lo + hi) // 2
            if self._newlines[mid] < off:
                lo = mid + 1
            else:
                hi = mid
        return lo + 1

    def frame_at(self, off):
        for f in self.frames:
            if f.start <= off < f.end:
                return f
        return None

    def where(self, off):
        f = self.frame_at(off)
        return (f.num if f else None), self.line_of(off)

    # -- parsing ------------------------------------------------------------
    def _parse(self):
        s = self.src
        doc = s.find("\\begin{document}")
        i = doc + len("\\begin{document}") if doc >= 0 else 0
        token = re.compile(
            r"\\begin\{frame\}|\\mlsystitle\b|\\section\*?(?=[\[{])|\\mlsysfocus\b|"
            r"\\mlsysmap\b|\\mlsysbackup\b|\\appendix\b|\\mlsysnote\b|\\mlsysdivider\b|\\note\b")
        frames, pending, divider, backup = [], None, "", False
        num = 0
        while True:
            m = token.search(s, i)
            if not m:
                break
            tok = m.group(0)
            if tok == "\\begin{frame}":
                end = self._frame_end(s, m.end())
                num += 1
                f = Frame(num, "frame", m.start(), end, self.line_of(m.start()))
                f.backup = backup
                self._fill_frame(f, s[m.end():end])
                frames.append(f)
                i = end
            elif tok == "\\mlsysnote":
                args, j = brace_args(s, m.end(), 1)
                if pending is not None:
                    self.findings_pre.append(("notes", m.start(),
                        "this \\mlsysnote replaces an earlier one that no theme frame used; the earlier note is lost"))
                pending = (args[0] if args else "", m.start())
                i = j
            elif tok == "\\mlsysdivider":
                args, j = brace_args(s, m.end(), 2)
                divider = " ".join(args)
                i = j
            elif tok == "\\note":
                self.findings_pre.append(("notes", m.start(),
                    "\\note outside a frame; Beamer drops it (use \\mlsysnote before a theme frame)"))
                _, j = brace_args(s, m.end(), 1)
                i = j
            elif tok in ("\\mlsysbackup", "\\appendix"):
                backup = True
                if tok == "\\mlsysbackup":
                    num += 1
                    f = Frame(num, "backup", m.start(), m.end(), self.line_of(m.start()))
                    f.backup = True
                    frames.append(f)
                i = m.end()
            else:
                nargs = {"\\mlsystitle": 3, "\\mlsysfocus": 2, "\\mlsysmap": 2}.get(tok, 1)
                args, j = brace_args(s, m.end(), nargs)
                num += 1
                kind = {"\\mlsystitle": "title", "\\mlsysfocus": "focus", "\\mlsysmap": "map"}.get(tok, "section")
                f = Frame(num, kind, m.start(), j, self.line_of(m.start()))
                f.backup = backup
                if kind == "title":
                    f.title = args[0] if args else ""
                    f.text = detex(" ".join(args[:2]))
                    f.image = args[2] if len(args) > 2 else ""
                elif kind == "focus":
                    f.title = args[0] if args else ""
                    f.text = detex(" ".join(args))
                elif kind == "map":
                    f.title = args[1] if len(args) > 1 else ""
                    f.text = detex(f.title)
                else:
                    f.title = args[0] if args else ""
                    f.text = detex(f.title + " " + divider)
                    divider = ""
                if kind in ("title", "focus", "section") and pending is not None:
                    f.notes.append(pending)
                    pending = None
                frames.append(f)
                i = j
        return frames

    def _attach_figure_text(self):
        """Read the <text> labels of every SVG a frame shows (images/, the
        shared kit), so a concept drawn in a figure counts as on the slide."""
        import html as _html
        svgs = {}
        for d in (self.path / "images", ROOT / "assets" / "kit" / self.volume):
            if d.exists():
                for p in d.glob("*.svg"):
                    svgs.setdefault(p.stem, p)
        cache = {}

        def labels(p):
            if p not in cache:
                t = p.read_text(errors="replace")
                parts = re.findall(r"<text\b[^>]*>(.*?)</text>", t, re.S)
                cache[p] = _html.unescape(" ".join(re.sub(r"<[^>]+>", " ", x) for x in parts))
            return cache[p]

        for f in self.frames:
            body = self.src[f.start:f.end]
            if f.kind == "title":
                continue
            used = set()
            for m in re.finditer(r"\{([A-Za-z0-9_./-]+)\}(?:\s*\{(\d+)\})?", body):
                name = Path(m.group(1)).stem if "." in Path(m.group(1)).name else Path(m.group(1)).name
                if name in svgs:
                    used.add(name)
                elif m.group(2):   # \mlsyssteps{prefix}{n}
                    used.update(k for k in (f"{name}{i}" for i in range(1, int(m.group(2)) + 1)) if k in svgs)
            f.figtext = " ".join(labels(svgs[n]) for n in sorted(used))

    @staticmethod
    def _frame_end(s, i):
        depth = 1
        pat = re.compile(r"\\begin\{frame\}|\\end\{frame\}")
        while True:
            m = pat.search(s, i)
            if not m:
                return len(s)
            depth += 1 if m.group(0).startswith("\\begin") else -1
            i = m.end()
            if depth == 0:
                return m.end()

    def _fill_frame(self, f, body):
        base = f.start + len("\\begin{frame}")
        # Title: \begin{frame}[opts]<ov>{Title} or \frametitle{...}
        j = 0
        while j < len(body) and body[j] in " \t\n[<":
            if body[j] == "[":
                j = body.find("]", j) + 1
            elif body[j] == "<":
                j = body.find(">", j) + 1
            else:
                j += 1
        if j < len(body) and body[j] == "{":
            k = match_brace(body, j)
            f.title = body[j + 1:k - 1]
            rest_from = k
        else:
            rest_from = 0
            mt = re.search(r"\\frametitle\{", body)
            if mt:
                k = match_brace(body, mt.end() - 1)
                f.title = body[mt.end():k - 1]
        rest = body[rest_from:]
        cut = []   # spans of rest to remove from slide text
        for m in re.finditer(r"\\note\b", rest):
            args, k = brace_args(rest, m.end(), 1)
            if args:
                f.notes.append((args[0], base + rest_from + m.start()))
                cut.append((m.start(), k))
        for m in re.finditer(r"\\mlsyscredit\b", rest):
            args, k = brace_args(rest, m.end(), 1)
            if args:
                f.credits.append(args[0])
                cut.append((m.start(), k))
        m = re.search(r"\\mlsysactivity\s*\{([^}]*)\}\s*\{([^}]*)\}", rest)
        if m:
            f.activity = (m.group(1), m.group(2))
        keep, last = [], 0
        for a, b in sorted(cut):
            keep.append(rest[last:a])
            last = max(last, b)
        keep.append(rest[last:])
        f.text = detex(f.title + " " + "".join(keep))


