class Volume:
    def __init__(self, voldir, concepts_root=None):
        self.dir = Path(voldir)
        self.name = self.dir.name
        folders = sorted((p for p in self.dir.iterdir()
                          if p.is_dir() and re.match(r"\d+[a-z]?_", p.name)
                          and list(p.glob("*.tex"))),
                         key=lambda p: order_key(p.name))
        self.decks = [Deck(p) for p in folders]
        self.by_id = {d.id: d for d in self.decks}
        self.book = None
        roots = [Path(concepts_root)] if concepts_root else BOOK_ROOTS.get(self.name, [])
        for r in roots:
            if r.exists():
                self.book = r
                break
        self._index = None
        self._strong = {}

    def next_deck(self, deck):
        i = self.decks.index(deck)
        return self.decks[i + 1] if i + 1 < len(self.decks) else None

    def sibling(self, lid):
        """'4' <-> '4b'."""
        if lid.endswith("b"):
            return lid[:-1]
        return lid + "b"

    def concept_map(self, chapter):
        if not self.book:
            return None
        hits = sorted((self.book / chapter).glob("*_concepts.yml"))
        if not hits:
            return None
        try:
            return (yaml.safe_load(hits[0].read_text()) or {}).get("concept_map")
        except yaml.YAMLError:
            return None

    # -- ownership index for callbacks ---------------------------------------
    def index(self):
        """Per lecture, the words of what its map says it teaches: title,
        subtitle, thesis, driving question, segment names, divider questions
        and landings, concept questions, worked-example names, and the
        coverage's primary_taught. Pictures, numbers, notes and hand-offs are
        left out: they name other lectures' topics too."""
        if self._index is None:
            idx = {}
            for d in self.decks:
                m = d.map
                parts = [str(m.get(k, "")) for k in ("title", "subtitle", "thesis", "driving_question")]
                for seg in m.get("segments") or []:
                    if isinstance(seg, dict):
                        parts += [str(seg.get(k, "")) for k in ("name", "divider_question", "divider", "land", "focus")]
                for q in m.get("concept_questions") or []:
                    parts.append(str(q.get("q", "")) if isinstance(q, dict) else str(q))
                for w in m.get("worked_examples") or []:
                    parts.append(str(w.get("name", "")) if isinstance(w, dict) else str(w))
                cov = m.get("coverage") or {}
                parts.append(str(cov.get("primary_taught", "")))
                idx[d.id] = wordset(" ".join(parts))
                # What the lecture is about, in a few words: title, subtitle,
                # segment names, and the names of the concepts it teaches.
                strong = [str(m.get("title", "")), str(m.get("subtitle", ""))]
                strong += [str(seg.get("name", "")) for seg in m.get("segments") or [] if isinstance(seg, dict)]
                strong += [re.sub(r"\(.*", "", str(c)) for c in cov.get("primary_taught") or []]
                self._strong[d.id] = wordset(" ".join(strong))
            self._index = idx
        return self._index

    def strong(self):
        self.index()
        return self._strong


