#!/usr/bin/env python3
"""Pre-review checker for lecture decks: the mechanical defects reviews keep finding.

Run it after every build, before a human or reviewer looks. It reads the
deck's .tex, lecture_map.yml, images/ and make_figs.py, the other decks of
the volume, the SVG figures' text labels, and the chapter's concept map. It
does not build or render anything; pair it with fitcheck.py (overflow and
bleed per page) and a look at every page.

Usage (from slides/; needs PyYAML and Pillow, e.g. the MLSysBook .venv):
    python3 tools/deckcheck.py vol1/10b_model_compression
    python3 tools/deckcheck.py vol1/10_model_compression vol1/10b_model_compression
    python3 tools/deckcheck.py --all vol1       every deck of one volume
    python3 tools/deckcheck.py --all            every deck of every volume
Options: --errors-only, --rule ID (repeatable), --summary (counts per rule),
--concepts-root DIR (the volume's book source, holding <chapter>/*_concepts.yml).

Output: one line per finding,
    <volume>/<deck> slide <N> (line <L>) <error|warning> <rule>: <detail>
N is the handout page: every frame counts as one, including the title, the
section dividers and the focus slides the theme builds ("deck" when the
finding is not tied to one slide; "[file:line]" for make_figs.py and
lecture_map.yml). Exit status 1 if any error is found, 0 otherwise. Fix every
error before review; read every warning and fix the ones that are right.

Rules
-----
cover          (error)   The title slide image must be a *_blueprint.png or a
                         photo credited in images/SOURCES.yml or
                         assets/photos/SOURCES.yml. An old generated
                         cover_<chapter>.png (garbled baked-in text), a labeled
                         print cover, or any other image is an error.
               (warning) The file is the clean blueprint under an old name
                         (matched against the book's covers by thumbnail).
callbacks      (error)   Every "Lecture N", "Lectures N and Mb", "Lecture Nb's"
                         in slide text, notes, credits, comments, make_figs.py
                         and lecture_map.yml names a deck of the volume.
               (warning) The words beside a mention name a topic that the
                         cited lecture's other part owns (its title, segment
                         names, or taught concepts: PSI, drift, monitoring,
                         ...) and that the cited lecture's map never mentions,
                         so the callback probably names the wrong part.
next-lecture   (error)   The closing "NEXT LECTURE | ..." label names the next
                         deck in teaching order (00, 01, ..., NN, NNb, ...),
                         by that deck's lecture_map title in capitals (a
                         leading "THE" is optional). The last deck has none.
unused-images  (error)   A file git ships in images/ that the .tex does not
                         show: unused by both the .tex and make_figs.py (the
                         logic of tools/unused_images.py), or generated by
                         make_figs.py but never shown (often a figure that
                         moved to the other part). Ignored build products
                         (an SVG's PDF) are skipped.
               (warning) make_figs.py still has a generator whose output is
                         neither on disk nor used.
style          (error)   An em dash (the character or ---) in slide text,
                         notes, credits or titles; a British spelling (colour,
                         behaviour, optimise, centre, modelling, labelled,
                         cancelled, ...).
               (warning) A hype word (crucial, massive, game-changing,
                         revolutionary, unprecedented, cutting-edge) outside
                         credits; an em dash used as an empty table cell.
notes          (error)   Every frame has a note that opens with [N min]; every
                         content note carries [CORE] or [OPTIONAL] (anywhere,
                         usually in FLEX); notes total 68 to 73 minutes; no
                         note over 220 words (the notes PDF cuts it off
                         silently); no \\note between frames and no
                         \\mlsysnote replaced before a theme frame uses it.
               (warning) Untagged title, divider, or closing notes
                         (takeaways, open questions, reading, next lecture).
activity       (error)   At least 3 \\mlsysactivity frames, and no stretch of
                         more than 16 minutes of note time without one (from
                         the start, between activities, or to the end).
               (warning) A stretch of 15 to 16 minutes.
title-vs-tag   (error)   An activity frame whose title runs into the activity
                         tag. Widths come from the Helvetica Bold metrics at
                         the frame-title size and the tag's own text
                         ("PREDICT · 2 min"); checked against rendered pages
                         (estimate within 1.5 percent; tag edge within 1 pt).
                         Lecture 10b slide 2's first title, "One INT8 recipe
                         keeps ResNet-50 and collapses MobileNetV2", runs 22 pt
                         in; "The same INT8 recipe keeps ResNet-50, not
                         MobileNetV2" clears it by 5 pt.
               (warning) Less than 3 pt of clearance.
concepts       (warning) A primary concept of the chapter's concept map that
                         no slide names: one frame's text and figure labels
                         must hold its key words (all of a one- or two-word
                         name, 60 percent of a longer one). Notes do not count.
                         For a two-part chapter, a concept goes to the part
                         whose coverage lists it as taught or touched.
numbers-basis  (warning) A recurring quantity (H100 memory, HBM bandwidth,
                         dense FP16 peak, FP16 ridge, power; decode arithmetic
                         intensity; DRAM energy per access and DRAM-to-
                         arithmetic ratios; GPT-2 XL FP16 weights; A100 FP16
                         peak) with a different value on the same basis
                         elsewhere in the volume. State the basis or align it.

What it cannot see: anything on the rendered page (run fitcheck.py and look),
whether a number is right, and whether a slide teaches its idea.
"""

