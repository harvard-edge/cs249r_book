APPROX = re.compile(r"(about|over|more than|nearly|almost|roughly|around|up to|under|at least|~|nearly)\s*$", re.I)


MULTI = r"[Tt]wo [A-Z]\d{3}s|\b\d+ ?[×x]? ?[A-Z]\d{3}s\b|\b[A-Z]\d{3}s together|per node|eight GPUs"


def sentences(text):
    return [x for x in re.split(r"(?<=[.;!?])\s+(?=[A-Z0-9\\])|\n\n", text) if x.strip()]


def device_ok(dev, sent, frame_all):
    others = re.compile(OTHER_DEVICES.replace(r"|%s\b" % dev, ""))
    other = r"(?:%s)" % "|".join(x for x in OTHER_DEVICES.split("|") if not x.startswith(dev))
    if re.search(dev, sent):
        return not re.search(other, sent)
    return bool(re.search(dev, frame_all)) and not re.search(other, frame_all)


def extract_quantities(deck):
    """Yield (qid, value, basis, approx, frame, sentence)."""
    for f in deck.frames:
        chunks = [f.text, detex(f.note)] + [detex(c) for c in f.credits]
        frame_all = " ".join(chunks)
        for chunk in chunks:
            for sent in sentences(chunk):
                for q in QUANTITIES:
                    if not re.search(q["need"], sent) or re.search(q["skip"], sent):
                        continue
                    if q.get("device") and not device_ok(q["device"], sent, frame_all):
                        continue
                    if q.get("device") and not re.search(q["device"], sent) and re.search(MULTI, frame_all):
                        continue   # the frame adds up several devices; the sentence may too
                    for m in re.finditer(r"(?<![\w.,])(?:%s)" % q["value"], sent):
                        raw = next((g for g in m.groups() if g and re.match(r"\d", g)), None)
                        if raw is None:
                            continue
                        v = float(raw.replace(",", ""))
                        unit = next((g for g in m.groups() if g and not re.match(r"\d", g)), "")
                        if unit.startswith("GB") and q["unit"] == "TB/s":
                            v /= 1000
                        if not (q.get("min", -1e18) <= v <= q.get("max", 1e18)):
                            continue
                        tags = [t for t, rx in q["basis"] if re.search(rx, sent)]
                        if not tags and q["basis"]:
                            ftags = [t for t, rx in q["basis"] if re.search(rx, frame_all)]
                            tags = ftags if len(ftags) == 1 else []
                        if not tags and q.get("require_basis"):
                            continue
                        basis = ",".join(tags) or "as stated"
                        approx = bool(APPROX.search(sent[:m.start()]))
                        yield q["id"], v, basis, approx, f, sent


def build_number_index(vol):
    if getattr(vol, "_numbers", None) is None:
        idx = defaultdict(list)
        for d in vol.decks:
            for qid, v, basis, approx, f, sent in extract_quantities(d):
                idx[(qid, basis)].append((v, approx, d, f, sent))
        vol._numbers = idx
    return vol._numbers


def same(a, b, rel=0.06):
    return abs(a - b) <= rel * max(abs(a), abs(b), 1e-9)


def rule_numbers(deck, vol, out):
    idx = build_number_index(vol)
    labels = {q["id"]: q for q in QUANTITIES}
    for (qid, basis), occ in idx.items():
        exact = [o for o in occ if not o[1]]
        if not exact:
            continue
        clusters = []
        for o in exact:
            for c in clusters:
                if same(c[0][0], o[0]):
                    c.append(o)
                    break
            else:
                clusters.append([o])
        if len(clusters) < 2:
            continue
        clusters.sort(key=lambda c: -len({o[2].id for o in c}))
        major = clusters[0]
        major_v = Counter(o[0] for o in major).most_common(1)[0][0]
        major_decks = sorted({o[2].id for o in major}, key=lambda x: order_key(f"{x}_"))
        q = labels[qid]
        for c in clusters[1:]:
            reported = set()
            for v, _, d, f, sent in c:
                if d is not deck or f.num in reported:
                    continue
                reported.add(f.num)
                out("numbers-basis", "warning", f.num, f.line,
                    f"{q['label']}{'' if basis == 'as stated' else ' (' + basis + ')'} is {v:g} {q['unit']} here "
                    f"but {major_v:g} in "
                    f"Lecture{'s' if len(major_decks) > 1 else ''} {', '.join(major_decks)}: \"{sent[:110]}\"")


