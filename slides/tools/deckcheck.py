def text_width(s, bold, size_pt):
    key = "phvb8a" if bold else "phvr8a"
    if key not in _METRICS:
        _METRICS[key] = _afm(key)
    w = _METRICS[key]
    if not w:
        avg = 611 if bold else 556
        return len(s) * avg * size_pt / 1000
    total = 0
    for c in s:
        total += w.get(GLYPH.get(c, c), 556)
    return total * size_pt / 1000


# Geometry (pt): 16:9 beamer is 453.54 pt wide; text margins 0.5 cm; the frame
# title is \large (14.4 pt at 12pt) in helvet scaled 0.9; the tag is \scriptsize
# (8 pt) bold, uppercase, inner xsep 7 pt, anchored 0.5 cm from the right edge.
PAPER_W, MARGIN = 453.54, 14.23
TITLE_PT, TAG_PT, TAG_PAD = 14.4 * 0.9, 8.0 * 0.9, 14.0
TITLE_FUDGE = 1.0
TAG_CLEAR_WARN = 3.0


def rule_title_tag(deck, vol, out):
    for f in deck.frames:
        if not f.activity or f.kind != "frame":
            continue
        title = detex(f.title)
        if not title:
            continue
        tag = f"{detex(f.activity[0]).upper()} · {detex(f.activity[1])}"   # \MakeUppercase on #1 only
        tw = text_width(title, True, TITLE_PT) * TITLE_FUDGE
        gw = text_width(tag, True, TAG_PT) + TAG_PAD
        room = (PAPER_W - MARGIN - gw) - MARGIN
        clear = room - tw
        if tw > PAPER_W - 2 * MARGIN:
            out("title-vs-tag", "error", f.num, f.line,
                f"title wraps to two lines and its first line runs under the {tag} tag: \"{title}\"")
        elif clear < 0:
            out("title-vs-tag", "error", f.num, f.line,
                f"title runs {-clear:.0f} pt into the {tag} tag (shorten it by about {int(-clear / 6.5) + 1} character{"s" if -clear > 6.5 else ""}): \"{title}\"")
        elif clear < TAG_CLEAR_WARN:
            out("title-vs-tag", "warning", f.num, f.line,
                f"title clears the {tag} tag by {clear:.0f} pt: \"{title}\"")


