# Close variants: a concept word also matches any of these slide words.
VARIANTS = {
    "dam": {"d·a·m"}, "ml": {"machine"}, "slo": {"deadline", "target"},
    "kv": {"key-value"}, "llm": {"language", "gpt", "llama"},
    "multiply": {"compound"}, "fast": {"speed", "speedup"},
    "fewer": {"less", "lower", "int8", "int4", "bit"},
    "tco": {"ownership", "lifetime"}, "lifecycle": {"lifetime", "life"},
    "gemm": {"matrix", "matmul"}, "nonlinearit": {"activation", "relu"},
    "tradeoff": {"trade"}, "jit": {"compile", "compiler", "torch.compile"},
}


def concept_terms(name):
    """Content words of a concept name, as roots; a hyphenated word is one term
    whose parts must all match."""
    out = []
    if "D·A·M" in name:
        out.append(("dam",))
        name = name.replace("D·A·M", " ")
    for w in words(name):
        if w.lower() in CONCEPT_STOP:
            continue
        parts = tuple(root(x) for x in re.split(r"[-']", w) if x and x.lower() not in CONCEPT_STOP)
        if parts:
            out.append(parts)
    return out


def frame_roots(f):
    if not hasattr(f, "_roots"):
        rs = set()
        for w in words(f.text + " " + f.figtext):
            rs.add(root(w))
            for part in re.split(r"[-']", w):
                if part:
                    rs.add(root(part))
        if "D·A·M" in f.text + f.figtext:
            rs.add("dam")
        f._roots = rs
    return f._roots


def term_in(part, roots):
    if part in roots:
        return True
    for v in VARIANTS.get(part, ()):
        if root(v) in roots:
            return True
    if len(part) >= 5:
        return any(r.startswith(part) or (len(r) >= 5 and part.startswith(r)) for r in roots)
    return False


def concept_found(terms, frames):
    """Named when one frame (its text and figure labels) holds at least 60
    percent of the concept's key words, and all of them for a one- or
    two-word name. Returns (found, best count, words the deck never shows)."""
    n = len(terms)
    need = n if n <= 2 else -(-3 * n // 5)
    best = 0
    for f in frames:
        rs = frame_roots(f)
        hit = sum(1 for t in terms if all(term_in(p, rs) for p in t))
        best = max(best, hit)
        if hit >= need:
            return True, best, []
    everywhere = set().union(*(frame_roots(f) for f in frames)) if frames else set()
    missing = ["-".join(t) for t in terms if not all(term_in(p, everywhere) for p in t)]
    return False, best, missing


def rule_concepts(deck, vol, out):
    cmap = vol.concept_map(deck.chapter)
    if cmap is None:
        if deck.id != "0" and vol.book:
            out("concepts", "warning", None, None, f"no concept map found for chapter {deck.chapter} under {vol.book}")
        return
    primaries = [str(c) for c in (cmap.get("primary_concepts") or [])]
    parts = [d for d in vol.decks if d.chapter == deck.chapter]

    def listed(d, c, keys):
        cov = d.map.get("coverage") or {}
        for k in keys:
            for entry in cov.get(k) or []:
                if str(entry).lower().startswith(c.lower()):
                    return True
        return False

    for c in primaries:
        terms = concept_terms(c)
        if not terms:
            continue
        if listed(deck, c, ("primary_left_to_reading",)):
            continue
        mine = listed(deck, c, ("primary_taught", "primary_touched"))
        others = [d for d in parts if d is not deck and listed(d, c, ("primary_taught", "primary_touched"))]
        if not mine and others:
            continue   # the other part carries it
        scope = [deck] if mine or len(parts) == 1 else parts
        if not mine and len(parts) > 1 and deck is not parts[0]:
            continue   # unassigned concepts are reported once, on Part 1
        frames = [f for d in scope for f in d.frames if not f.backup]
        ok, best, missing = concept_found(terms, frames)
        if not ok:
            where = "this deck's" if len(scope) == 1 else "either part's"
            why = f"no slide shows more than {best} of its {len(terms)} key words together"
            if missing:
                why += f"; never shows {', '.join(missing)}"
            out("concepts", "warning", None, None,
                f"primary concept \"{c}\" is not named in {where} slide text ({why})")


