"""Computed values for a deck's slides and notes.

A deck's images/calcs.py computes every number the deck shows, from MLSysIM
where MLSysIM holds the input and from cited sources otherwise. It records
each value with v() and calls write() at the end. write() produces
images/numbers.tex, which the deck reads with \\input{images/numbers.tex}, and
the slide text names each value as \\val{key}. The .tex stays the deck source;
numbers.tex is generated and committed, so the deck builds with LaTeX alone.

    from deckvals import v, write, mlsysim
    Hardware = mlsysim.Hardware
    v("h100_bw", Hardware.Cloud.H100.memory.bandwidth.to("TB/s").magnitude,
      "{:.2f}", "H100 HBM bandwidth, TB/s")
    write(__file__)

Keys are lowercase letters, digits, and underscores. A key the deck uses but
numbers.tex lacks stops the build with "Undefined value".
"""

import re
import sys
from pathlib import Path

# MLSysIM resolves from the repository folder; it is never pip-installed.
_REPO = Path(__file__).resolve().parents[3]
sys.path.insert(0, str(_REPO / "mlsysim"))
import mlsysim  # noqa: E402,F401

# Whole numbers below ten read as words in prose (house style).
_WORDS = ("zero", "one", "two", "three", "four", "five", "six", "seven", "eight", "nine")
_KEY = re.compile(r"^[a-z][a-z0-9_]*$")
_values = {}


def v(key, value, fmt="{:,.3g}", label=""):
    """Record one value, print it, and return the formatted string.

    fmt is a format string, or "words" to spell a whole number below ten.
    """
    if not _KEY.match(key):
        raise ValueError(f"key {key!r}: use lowercase letters, digits, underscores")
    if key in _values:
        raise ValueError(f"key {key!r} recorded twice")
    if fmt == "words":
        n = round(value)
        if abs(value - n) > 0.05 or not 0 <= n < len(_WORDS):
            raise ValueError(f"key {key!r}: {value} is not a small whole number")
        text = _WORDS[n]
    else:
        text = fmt.format(value)
    _values[key] = text
    print(f"{key:34s} {text:>12s}   {label}")
    return text


def val(key):
    """The formatted string recorded under key, for figure labels."""
    return _values[key]


def num(key):
    """The recorded value as a float, for plotting at the printed precision."""
    return float(_values[key].replace(",", ""))


def _tex(text):
    # A comma inside math adds a space after it; {,} prints a plain comma in
    # both text and math.
    return text.replace(",", "{,}")


def write(calcs_file):
    """Write images/numbers.tex beside the calling calcs.py."""
    out = Path(calcs_file).resolve().parent / "numbers.tex"
    lines = ["% Generated by calcs.py. Do not edit; edit calcs.py and rerun it.\n"]
    lines += [f"\\defval{{{k}}}{{{_tex(t)}}}\n" for k, t in _values.items()]
    out.write_text("".join(lines))
    print(f"wrote {out.name}: {len(_values)} values")
