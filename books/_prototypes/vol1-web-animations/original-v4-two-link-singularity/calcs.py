#!/usr/bin/env python3
"""Export canonical two-link geometry; reuse the chapter LEGO cell verbatim."""
import hashlib
import json
from pathlib import Path
import sys
import numpy as np
ROOT = Path(__file__).resolve().parents[4]
sys.path.insert(0, str(ROOT / "mlsysim"))
SOURCE = ROOT / "books/vol4/11_planning/11_planning.qmd"
text = SOURCE.read_text()
cell = text.split("#| label: calc-planning-two-link-arm", 1)[1].split("```", 1)[0]
namespace = {}
exec(compile(cell, str(SOURCE), "exec"), namespace)
TL = namespace["PlanningTwoLinkArm"]
l1, l2 = float(TL.l1.magnitude), float(TL.l2.magnitude)
speed, limit = float(TL.v_tool.magnitude), float(TL.qd_max.magnitude)

def sample(deg):
    q2 = np.radians(deg)
    q1 = np.pi / 4 - np.arctan2(l2 * np.sin(q2), l1 + l2 * np.cos(q2))
    elbow = l1 * np.array([np.cos(q1), np.sin(q1)])
    tool = elbow + l2 * np.array([np.cos(q1 + q2), np.sin(q1 + q2)])
    jac = np.array([[-tool[1], -l2*np.sin(q1+q2)], [tool[0], l2*np.cos(q1+q2)]])
    u, sig, vt = np.linalg.svd(jac)
    weak = u[:, -1]
    if weak @ tool < 0:
        weak = -weak
    velocity = speed * weak
    qdot = np.linalg.solve(jac, velocity)
    feasible = speed * limit / np.max(np.abs(qdot))
    assert np.isclose(np.linalg.norm(elbow), l1)
    assert np.isclose(np.linalg.norm(tool-elbow), l2)
    assert np.allclose(jac @ qdot, velocity, atol=1e-12)
    assert np.isclose(np.linalg.norm(qdot), speed/sig[-1])
    assert np.isclose(np.linalg.det(jac), l1*l2*np.sin(q2))
    assert np.max(np.abs(qdot * feasible / speed)) <= limit + 1e-12
    assert np.isclose(np.arctan2(tool[1], tool[0]), np.pi/4)
    return dict(angle=float(deg), q1=float(q1), elbow=elbow.tolist(), tool=tool.tolist(), jac=jac.tolist(), weak=weak.tolist(), sigma=sig.tolist(), velocity=velocity.tolist(), qdot=qdot.tolist(), norm=float(np.linalg.norm(qdot)), feasible=float(feasible))

samples = [sample(deg) for deg in np.linspace(90, 10, 801)]
assert round(samples[0]["norm"], 1) == round(TL.qd_norm_good.magnitude, 1)
assert round(samples[-1]["norm"], 1) == round(TL.qd_norm_bad.magnitude, 1)
assert all(a["norm"] < b["norm"] for a,b in zip(samples, samples[1:]))
data = dict(source="PlanningTwoLinkArm (chapter LEGO cell, loaded verbatim)", source_cell_sha256=hashlib.sha256(cell.encode()).hexdigest(), l1=l1, l2=l2, reach=float(TL.reach.magnitude), speed=speed, joint_limit=limit, ellipse_drawing_scale=0.25, samples=samples)
TARGET=ROOT / "books/_extensions/mlsysbook-ext/figure-explore/original-v4-two-link-singularity.data.js"
TARGET.write_text("/* Generated by original-v4-two-link-singularity/calcs.py. */\nwindow.MLSysTwoLinkSingularityData=" + json.dumps(data, separators=(",", ":")) + ";\n")
report=dict(samples=len(samples), endpoint_norms=[samples[0]["norm"],samples[-1]["norm"]], endpoint_joint_rates=[samples[0]["qdot"],samples[-1]["qdot"]], endpoint_feasible_speeds=[samples[0]["feasible"],samples[-1]["feasible"]], invariants="J qdot=v; norm=speed/sigma_min; determinant; fixed tool bearing; per-joint scaled limits; monotone norm", data_sha256=hashlib.sha256(TARGET.read_bytes()).hexdigest())
(Path(__file__).parent/"calculation-report.json").write_text(json.dumps(report,indent=2)+"\n")
print(json.dumps(report,indent=2))
