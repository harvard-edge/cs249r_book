#!/usr/bin/env python3
"""Export the existing normalized planning lesson on the original SVG coordinates."""
import json,runpy,sys,xml.etree.ElementTree as ET
from pathlib import Path
HERE=Path(__file__).resolve().parent
repo=HERE.parents[3]
source=HERE/'mechanisms/vol4-b.calc.py'
lesson=next(x for x in runpy.run_path(str(source))['build']() if x['key']=='vol4:fig-11-intersample-overshoot')
start=lesson['steps'][0]['snapshot']['objects']
a=start['acceleration']['series'][0]['points'][0][1]
limit=next(x for x in start['velocity']['series'] if x['id']=='limit')['points'][0][1]
near=next(x for x in start['velocity']['series'] if x['id']=='near')['points'][0][1]
safe=next(x for x in start['velocity']['series'] if x['id']=='safe')['points'][0][1]
duration=start['acceleration']['series'][0]['points'][-1][0]
reserve=a*duration/2
assert safe==limit-reserve
art=repo/'books/vol4/11_planning/images/svg/intersample_velocity_overshoot.svg'
svg=ET.parse(art).getroot();paths=[n.get('d') for n in svg.iter() if n.tag.endswith('path')]
assert 'M140 330 L370 270 L600 330' in paths and 'M140 360 L370 300 L600 360' in paths
# Map the source paths to the existing normalized values. No physical-unit registry.
x0,xmid,x1=140,370,600
vscale=(360-300)/(limit-safe);voffset=300+vscale*limit
assert voffset-vscale*near==330 and voffset-vscale*(near+reserve)==270
accelzero,accelscale=125,(125-70)/a
points=[]
for s in lesson['steps']:
 m={v['id']:v['value'] for v in s['snapshot']['metrics']};t=m['time']
 rise=a*min(t,duration-t);v=near+rise;vc=safe+rise
 assert v==m['near'] and vc==m['contracted']
 points.append(dict(time=t,rise=rise,bronze=v,pine=vc,x=x0+(x1-x0)*t/duration,bronze_y=voffset-vscale*v,pine_y=voffset-vscale*vc))
data=dict(source='mechanisms/vol4-b.calc.py:build',normalized=True,acceleration_bound=a,duration=duration,limit=limit,candidate_endpoint=near,contracted_endpoint=safe,reserve=reserve,geometry=dict(x0=x0,xmid=xmid,x1=x1,velocity_scale=vscale,velocity_offset=voffset,acceleration_zero=accelzero,acceleration_scale=accelscale),points=points)
target=HERE/'original-intersample-overshoot-data.js'
expected='// Generated by original-intersample-overshoot.calc.py from the existing normalized lesson.\nwindow.MLSysOriginalIntersampleData = '+json.dumps(data,ensure_ascii=False,indent=2)+';\n'
if '--write' in sys.argv:target.write_text(expected)
assert target.read_text()==expected,'Run exporter with --write after reviewing canonical changes'
print(json.dumps(data,indent=2))
