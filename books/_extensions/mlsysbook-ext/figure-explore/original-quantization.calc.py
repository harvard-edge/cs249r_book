"""Export the declared toy dot product. Rerun after changing any example value."""
from decimal import Decimal, ROUND_HALF_UP
from pathlib import Path
import json

def calculate():
    x = [Decimal('0.31'), Decimal('-0.52')]
    w = [Decimal('0.42'), Decimal('0.24')]
    sx = sw = Decimal('0.1')
    sy = Decimal('0.01')
    quantize = lambda a, s: [int((v/s).quantize(Decimal(1), rounding=ROUND_HALF_UP)) for v in a]
    qx, qw = quantize(x, sx), quantize(w, sw)
    products = [a*b for a,b in zip(qx,qw)]
    accumulator = sum(products)
    requantized = max(-128,min(127,int((Decimal(accumulator)*sx*sw/sy).quantize(Decimal(1),rounding=ROUND_HALF_UP))))
    output = max(0,requantized)
    return dict(x=list(map(float,x)), w=list(map(float,w)), sx=float(sx), sw=float(sw), sy=float(sy), qx=qx, qw=qw, products=products, accumulator=accumulator, requantized=requantized, output=output, reconstructed=float(Decimal(output)*sy), float_reference=float(sum(a*b for a,b in zip(x,w))))

if __name__ == '__main__':
    data=calculate()
    Path(__file__).with_name('original-quantization.data.js').write_text('// Generated by original-quantization.calc.py; do not edit numerical values.\nwindow.MLSysOriginalQuantizationData = '+json.dumps(data, separators=(',',':'))+';\n')
