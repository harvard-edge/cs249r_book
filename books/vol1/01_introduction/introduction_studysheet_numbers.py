"""Numbers for the Introduction study sheet (Volume I, Chapter 1).

Every value the sheet prints is computed here from mlsysim, as in the chapter's LEGO cells,
and written as \\setnum{key}{value} to introduction_studysheet_numbers.tex next to this file.
Inputs the sheet chooses for its questions are marked ASSUMED.
"""
import math
from pathlib import Path

from mlsysim import Hardware as HW, load_series
from mlsysim.engine.scenarios import Scenarios as SC


def g(x):
    return f"{x:g}"


def numbers() -> dict:
    n = {}
    tb = SC.IronLawComputeHeavyExample                                   # intro-time-budget
    m, c, o = (tb.result.memory_time.to("s").magnitude, tb.result.compute_time.to("s").magnitude,
               tb.result.overhead.to("s").magnitude)
    s = tb.compute_speedup
    n.update(m=g(m), c=g(c), o=g(o), s=g(s), tot=g(m + c + o), new=g(m + c / s + o),
             cnew=g(c / s), naive=g(round((m + c + o) / s, 2)))

    ap = SC.ModelSpeedupRequestPath                                       # amdahls-pitfall
    pre, mod, post = (ap.stages[k].to("ms").magnitude for k in ("preprocess", "model", "postprocess"))
    sp = ap.speedup
    a_tot, a_new = pre + mod + post, pre + mod / sp + post
    n.update(pre=g(pre), mod=g(mod), post=g(post), sp=g(sp), modnew=g(mod / sp), atot=g(a_tot),
             anew=g(a_new), ax=f"{a_tot / a_new:.1f}", apct=f"{(a_tot - a_new) / a_tot * 100:.0f}",
             prepost=g(pre + post))

    e_fp16 = HW.Tech.Op.FlopFp16.energy.to("pJ/flop").magnitude           # energy-movement-ratios
    e_dram = HW.Tech.Memory.DRAM.energy_per_byte.to("pJ/B").magnitude
    n.update(efp=g(e_fp16), edram=g(e_dram))

    ae = load_series("vol1/01_introduction/data/algorithmic_efficiency.csv").entries   # efficiency-gains
    algo_x = (next(e["tfs_days"] for e in ae if e["model"] == "AlexNet")
              / next(e["tfs_days"] for e in ae if e["model"] == "EfficientNet-B0"))
    ct = load_series("vol1/01_introduction/data/compute_trend.csv").entries           # training-compute-growth-summary
    growth = round(math.log10(next(e["flops"] for e in ct if e["model"] == "GPT-4-class")
                              / next(e["flops"] for e in ct if e["model"] == "AlexNet")))
    n.update(algox=f"{algo_x:.0f}", growth=str(growth))

    vg = SC.ImageNetInputSpace                                           # verification-gap-calc
    digits = math.floor(int(vg.elements) * round(math.log10(int(vg.levels)), 5)) + 1
    n.update(vgdigits=f"{digits:,}", vgtest=f"{int(vg.test_examples):,}")

    acc0, drop, months = 85.0, 0.8, 6                                    # drift-fallacy (chapter scenario)
    n.update(acc0=g(acc0), drop=g(drop), months=g(months), accfinal=f"{acc0 - drop * months:.1f}")

    # ASSUMED inputs for check-yourself question 1
    gb, bw, gf, rate, ovh, qx = 6, 2_000, 400, 100_000, 1, 2   # GB, GB/s, GFLOP, GFLOP/s, ms, math speedup
    qm, qc = gb / bw * 1e3, gf / rate * 1e3
    em, ec = gb * 1e9 * e_dram * 1e-12, gf * 1e9 * e_fp16 * 1e-12
    n.update(qgb=g(gb), qtbs=g(bw / 1000), qgf=g(gf), qtfs=g(rate / 1000), qo=g(ovh), qm=g(qm), qc=g(qc),
             qseq=g(qm + qc + ovh), qmax=g(max(qm, qc)), qovl=g(max(qm, qc) + ovh), qi=f"{gf / gb:.0f}",
             qbal=g(rate / bw), qx=g(qx), qcfast=g(qc / qx), qmo=g(max(qm, qc / qx) + ovh), qem=f"{em:.2f}", qec=f"{ec:.2f}",
             qer=f"{em / ec:.1f}")

    # ASSUMED inputs for question 3 (return on compute)
    ga, ca, gb_, cb, per, worth = 1.5, 15_000, 4.0, 100_000, 10_000, 20_000
    n.update(ga=g(ga), ca=f"{ca:,}", gb=g(gb_), cb=f"{cb:,}", worth=f"{worth:,}", per=f"{per:,}",
             roca=f"{ga / ca * per:.1f}", rocb=f"{gb_ / cb * per:.1f}", rocbe=f"{per / worth:.1f}")
    return n


if __name__ == "__main__":
    out = Path(__file__).with_suffix(".tex")
    out.write_text("% generated by " + Path(__file__).name + "; do not edit\n"
                   + "".join(f"\\setnum{{{k}}}{{{v}}}\n" for k, v in numbers().items()))
    print(out)
