"""Numbers for the Data Engineering study sheet (Volume I, Chapter 4).

Every value the sheet prints is computed here from mlsysim's scenarios, as in the chapter's LEGO cells,
and written as \\setnum{key}{value} to data_engineering_studysheet_numbers.tex next to this file.
Inputs the sheet chooses for its own questions are marked ASSUMED.
"""
from pathlib import Path

from mlsysim.engine.scenarios import Scenarios as SC


def g(x):
    return f"{x:g}"


def c(x):
    return f"{x:,.0f}".replace(",", "{,}")


def numbers() -> dict:
    n = {}

    # ---- Worked example: the feeding problem (FeedingProblem cell): ResNet-50 on one A100,
    # 150 KB JPEGs read from a baseline cloud block volume every epoch.
    f = SC.ResNet50A100InputFeed
    rate = f.sustained_rate.to("1/s").magnitude                 # img/s the accelerator sustains
    ceil = f.ceiling_rate.to("1/s").magnitude                   # img/s compute ceiling
    jpg_kb = f.encoded_sample.to("kB").magnitude
    disk = f.supply.bandwidth.to("MB/s").magnitude
    need = rate * jpg_kb / 1000                                 # MB/s demand in compressed bytes
    assert abs(need - f.demand().to("MB/s").magnitude) < 1e-6
    got = disk / (jpg_kb / 1000)                                # img/s the disk supplies
    loss = 1 - got / rate
    assert abs(loss - f.feeding_loss()) < 1e-9
    n.update(rate=c(rate), ceil=c(ceil), jpgkb=c(jpg_kb), disk=c(disk), need=c(need),
             got=c(got), loss=f"{loss * 100:.0f}", ratiopct=f"{got / rate * 100:.0f}")

    # ---- Your turn: same disk, but a cache of pre-decoded FP32 tensors (224x224x3 x 4 bytes)
    dec_kb = f.decoded_sample.to("kB").magnitude
    yneed = rate * dec_kb / 1e6                                 # GB/s
    assert abs(yneed - f.demand(decoded=True).to("GB/s").magnitude) < 1e-9
    ygot = disk / (dec_kb / 1000)
    yloss = 1 - ygot / rate
    assert abs(yloss - f.feeding_loss(decoded=True)) < 1e-9
    n.update(deckb=c(dec_kb), expand=f"{dec_kb / jpg_kb:.0f}", yneed=f"{yneed:.2f}", ygot=c(ygot),
             yloss=f"{yloss * 100:.0f}")

    # ---- Front card and Q1: the false-wake budget (FalsePositiveTarget, ListeningHours cells)
    fw = SC.KeywordSpotterFalseWakes
    win = fw.windows
    fpr = fw.target_false_positive_rate
    assert abs(fpr - fw.budget / win) < 1e-15
    ev = SC.KeywordSpotterFalseWakeEvidence
    hrs = ev.exposure_needed.to("hour").magnitude                # ~ 3 / (1 per 720 h)
    mant, ex = f"{fpr:.1e}".split("e")
    n.update(fwwin=c(win), fwfpr=f"{mant}\\times 10^{{{int(ex)}}}", fwhours=c(round(hrs, -1)),
             fwmonthh=c(ev.horizon.to("hour").magnitude), fwthree=f"{ev.events_bound:.0f}",
             fwconf=f"{ev.confidence * 100:.0f}")

    # Q1 ASSUMED: a looser budget of one false wake per week, one-second windows, always on
    q_per_week, sec_per_week = 1, 7 * 24 * 3600
    qfpr = q_per_week / sec_per_week
    qm, qe = f"{qfpr:.2e}".split("e")
    q_hours = round(ev.events_bound) / (q_per_week / (7 * 24))   # rule of three: 3 / (rate per hour)
    n.update(qwin=c(sec_per_week), qfpr=f"{qm}\\times 10^{{{int(qe)}}}", qweekh=g(7 * 24), qhours=c(q_hours),
             qweeks=g(q_hours / (7 * 24)), one=g(q_per_week))

    # Q4 ASSUMED: drop in measured detection rate six months after launch (chapter scenario says four points)
    n.update(q4drop=g(4), q4months=g(6))

    # ---- Mistake 1: tenfold data (KWSDesignSpaceTradeoffs), and labeling vs one training run (LabelingComputeRatio)
    ex = SC.KeywordSpotterExampleCountChoice
    n.update(moregainlo=f"{ex.gain_low * 100:.0f}", moregainhi=f"{ex.gain_high * 100:.0f}", morex=f"{ex.ratio:.0f}")
    run = SC.ImageNetLabelingVersusResNetRun
    n.update(labratlo=c(round(run.ratio_low, -2)), labrathi=c(round(run.ratio_high, -2)))

    # ---- Q4: PSI bands (chapter conventions, tbl-data-debt-metrics) and an ASSUMED observed PSI
    psi_warn, psi_crit, psi_obs = 0.1, 0.25, 0.31
    n.update(psiwarn=g(psi_warn), psicrit=g(psi_crit), psiobs=g(psi_obs))
    return n


if __name__ == "__main__":
    out = Path(__file__).with_suffix(".tex")
    out.write_text("% generated by " + Path(__file__).name + "; do not edit\n"
                   + "".join(f"\\setnum{{{k}}}{{{v}}}\n" for k, v in numbers().items()))
    print(out)
