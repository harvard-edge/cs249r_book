"""Render the landing inventory from the same catalogs that own each lab shell."""
from __future__ import annotations
import argparse
import html
from pathlib import Path

from build_lab_shells import ROMAN, VOLUME_ACCENTS, discover


def inventory(labs: Path) -> str:
    entries = discover(labs)
    esc = html.escape
    lines = ['<!-- Generated by tools/build_lab_inventory.py from packaged learning paths. -->', '', '```{=html}', '<div class="volume-inventory">']
    for volume in sorted({row['volume'] for row in entries}):
        rows = [row for row in entries if row['volume'] == volume]
        first = rows[0]
        if first['chapter'] != 0:
            raise ValueError(f'Volume {ROMAN[volume]} must start with Lab 00 onboarding')
        lines += [f'<section class="volume-inventory-card" style="--volume-accent:{VOLUME_ACCENTS[volume]}" aria-labelledby="volume-{volume}-title">',
                  f'<h3 id="volume-{volume}-title">Volume {ROMAN[volume]}</h3>',
                  f'<p class="inventory-count">Onboarding + {len(rows) - 1} chapter labs</p>',
                  f'<p><a class="inventory-start" href="{first["route"]}/" aria-label="Start Volume {ROMAN[volume]} onboarding at Lab 00">Start Lab 00 <span aria-hidden="true">→</span></a></p>',
                  f'<details><summary>Explore the Volume {ROMAN[volume]} route</summary><ol class="inventory-route">']
        for row in rows:
            # Goals are authored in concept maps and packaged by build_learning_paths;
            # the landing page must not create its own competing teaser claims.
            goal = row.get('goal') or row['learning_objectives'][0]
            lines += [f'<li><a href="{row["route"]}/"><span class="inventory-lab-number">{row["chapter"]:02d}</span> {esc(row["title"])}</a><p>{esc(goal)}</p></li>']
        lines += ['</ol></details></section>']
    lines += ['</div>', '```', '']
    return '\n'.join(lines)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    labs = Path(__file__).resolve().parents[1]
    path = labs / 'config/lab-inventory.qmd'
    content = inventory(labs)
    if args.check:
        if not path.exists() or path.read_text() != content:
            raise SystemExit('Lab inventory is stale; run labs/tools/build_lab_inventory.py')
        print('Canonical lab inventory is current')
    else:
        if not path.exists() or path.read_text() != content:
            path.write_text(content)
        print(f'Generated {path.relative_to(labs)}')


if __name__ == '__main__':
    main()
