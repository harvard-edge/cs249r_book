def install(labs: Path, output: Path) -> int:
    """Decorate exported apps once; keep canonical entry URLs as launchers."""
    import re
    entries = discover(labs)
    chrome = shared_header(output)
    theme = output / 'assets/styles/notebook-theme.css'
    theme.parent.mkdir(parents=True, exist_ok=True)
    theme.write_text((labs / 'assets/styles/notebook-theme.css').read_text())
    scripts = output / 'assets/scripts'
    scripts.mkdir(parents=True, exist_ok=True)
    (scripts / 'notebook-chrome.js').write_text((labs / 'assets/scripts/notebook-chrome.js').read_text())
    (scripts / 'theme-persist.js').write_text((labs.parent / 'shared/scripts/theme-persist.js').read_text())
    for entry in entries:
        family = [row for row in entries if row['volume'] == entry['volume']]
        index = family.index(entry)
        head, nav = fullpage_navigation(labs, entry, family[index-1] if index else None,
                                        family[index+1] if index+1 < len(family) else None, chrome)
        target = output / entry['route'] / 'app/index.html'
        text = target.read_text()
        for name in ('HEAD', 'NAV'):
            text = re.sub(r'<!-- LAB-FULLPAGE-' + name + r' -->.*?<!-- /LAB-FULLPAGE-' + name + r' -->', '', text, flags=re.S)
        if '</head>' not in text or not re.search(r'<body\b[^>]*>', text):
            raise ValueError(f'Invalid exported app: {target}')
        text = text.replace('</head>', head + '</head>', 1)
        text = re.sub(r'(<body\b[^>]*>)', lambda match: match[1] + nav, text, count=1)
        target.write_text(text)
        title = html.escape(f"Lab {entry['chapter']:02d} · {entry['title']}")
        (target.parent.parent / 'index.html').write_text(
            '<!doctype html><html lang="en"><head><meta charset="utf-8">'
            '<meta name="viewport" content="width=device-width, initial-scale=1">'
            f'<title>{title}</title>{REDIRECT_SCRIPT}</head><body>'
            f'<p><a href="app/index.html">Open {title}</a></p></body></html>')
    return len(entries)


def prepare(labs: Path, manifest: Path) -> int:
    entries = discover(labs)
    generated = []
    # Validate every destination before writing any generated source.
    for entry in entries:
        target = labs / entry["route"] / "index.qmd"
        if target.exists() and MARKER not in target.read_text():
            raise ValueError(f"Refusing to overwrite authored source: {target}")
    for entry in entries:
        same_volume = [row for row in entries if row["volume"] == entry["volume"]]
        index = same_volume.index(entry)
        previous = same_volume[index - 1] if index else None
        following = same_volume[index + 1] if index + 1 < len(same_volume) else None
        target = labs / entry["route"] / "index.qmd"
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(shell(labs, entry, previous, following))
        generated.append(target.relative_to(labs).as_posix())
    manifest.parent.mkdir(parents=True, exist_ok=True)
    manifest.write_text(json.dumps({"files": generated, "volumes": sorted({r["volume"] for r in entries})}, indent=2) + "\n")
    return len(generated)


def cleanup(labs: Path, manifest: Path) -> None:
    if not manifest.exists():
        return
    for relative in json.loads(manifest.read_text())["files"]:
        target = (labs / relative).resolve()
        if not target.is_relative_to(labs.resolve()) or target.name != "index.qmd":
            raise ValueError(f"Unsafe generated-source cleanup: {target}")
        if target.exists():
            if MARKER not in target.read_text():
                raise ValueError(f"Generated file was replaced by authored content: {target}")
            target.unlink()
        # Only remove an empty transient route directory. Never recurse.
        try:
            target.parent.rmdir()
        except OSError:
            pass


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("action", choices=("prepare", "cleanup", "list", "install"))
    parser.add_argument("--labs-dir", type=Path, default=Path(__file__).resolve().parents[1])
    parser.add_argument("--output-dir", type=Path)
    args = parser.parse_args()
    labs = args.labs_dir.resolve()
    manifest = labs / "_wasm_build/shell-manifest.json"
    if args.action == "install":
        print(f"Installed {install(labs, args.output_dir or labs / '_build')} full-page notebooks")
    elif args.action == "prepare":
        print(f"Generated {prepare(labs, manifest)} Quarto lab shells")
    elif args.action == "cleanup":
        cleanup(labs, manifest)
    else:
        for row in discover(labs):
            print(row["route"])


if __name__ == "__main__":
    main()
